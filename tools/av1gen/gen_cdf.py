#!/usr/bin/env python3
"""Generate cdf_gen.go: the CDF context struct and its initialisers."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import spectables as S

OUT = sys.argv[1] if len(sys.argv) > 1 else "cdf_gen.go"

def goname(n):
    p = n.split("_")
    return p[0].lower() + "".join(x[:1].upper() + x[1:] for x in p[1:])

# (field, spec table, replicate-prefix dims)
NONCOEF = [
 ("intraFrameYMode","Default_Intra_Frame_Y_Mode_Cdf",()), ("yMode","Default_Y_Mode_Cdf",()), ("uvModeCflNotAllowed","Default_Uv_Mode_Cfl_Not_Allowed_Cdf",()),
 ("uvModeCflAllowed","Default_Uv_Mode_Cfl_Allowed_Cdf",()), ("angleDelta","Default_Angle_Delta_Cdf",()),
 ("intrabc","Default_Intrabc_Cdf",()),
 ("partitionW8","Default_Partition_W8_Cdf",()), ("partitionW16","Default_Partition_W16_Cdf",()),
 ("partitionW32","Default_Partition_W32_Cdf",()), ("partitionW64","Default_Partition_W64_Cdf",()),
 ("partitionW128","Default_Partition_W128_Cdf",()),
 ("segmentID","Default_Segment_Id_Cdf",()), ("segmentIDPredicted","Default_Segment_Id_Predicted_Cdf",()),
 ("tx8x8","Default_Tx_8x8_Cdf",()), ("tx16x16","Default_Tx_16x16_Cdf",()), ("tx32x32","Default_Tx_32x32_Cdf",()),
 ("tx64x64","Default_Tx_64x64_Cdf",()), ("txfmSplit","Default_Txfm_Split_Cdf",()),
 ("filterIntraMode","Default_Filter_Intra_Mode_Cdf",()), ("filterIntra","Default_Filter_Intra_Cdf",()),
 ("interpFilter","Default_Interp_Filter_Cdf",()), ("motionMode","Default_Motion_Mode_Cdf",()),
 ("newMv","Default_New_Mv_Cdf",()), ("zeroMv","Default_Zero_Mv_Cdf",()), ("refMv","Default_Ref_Mv_Cdf",()),
 ("compoundMode","Default_Compound_Mode_Cdf",()), ("drlMode","Default_Drl_Mode_Cdf",()),
 ("isInter","Default_Is_Inter_Cdf",()), ("compMode","Default_Comp_Mode_Cdf",()),
 ("skipMode","Default_Skip_Mode_Cdf",()), ("skip","Default_Skip_Cdf",()),
 ("compRef","Default_Comp_Ref_Cdf",()), ("compBwdRef","Default_Comp_Bwd_Ref_Cdf",()),
 ("singleRef","Default_Single_Ref_Cdf",()),
 ("mvJoint","Default_Mv_Joint_Cdf",(2,)), ("mvClass","Default_Mv_Class_Cdf",(2,)),
 ("mvClass0Bit","Default_Mv_Class0_Bit_Cdf",(2,2)), ("mvFr","Default_Mv_Fr_Cdf",(2,)),
 ("mvClass0Fr","Default_Mv_Class0_Fr_Cdf",(2,)), ("mvClass0Hp","Default_Mv_Class0_Hp_Cdf",(2,2)),
 ("mvSign","Default_Mv_Sign_Cdf",(2,2)), ("mvBit","Default_Mv_Bit_Cdf",(2,2)), ("mvHp","Default_Mv_Hp_Cdf",(2,2)),
 ("paletteYMode","Default_Palette_Y_Mode_Cdf",()), ("paletteUVMode","Default_Palette_Uv_Mode_Cdf",()),
 ("paletteYSize","Default_Palette_Y_Size_Cdf",()), ("paletteUVSize","Default_Palette_Uv_Size_Cdf",()),
] + [("paletteSize%dYColor" % n, "Default_Palette_Size_%d_Y_Color_Cdf" % n, ()) for n in range(2, 9)] \
  + [("paletteSize%dUVColor" % n, "Default_Palette_Size_%d_Uv_Color_Cdf" % n, ()) for n in range(2, 9)] + [
 ("deltaQ","Default_Delta_Q_Cdf",()), ("deltaLF","Default_Delta_Lf_Cdf",()), ("deltaLFMulti","Default_Delta_Lf_Cdf",(4,)),
 ("intraTxTypeSet1","Default_Intra_Tx_Type_Set1_Cdf",()), ("intraTxTypeSet2","Default_Intra_Tx_Type_Set2_Cdf",()),
 ("interTxTypeSet1","Default_Inter_Tx_Type_Set1_Cdf",()), ("interTxTypeSet2","Default_Inter_Tx_Type_Set2_Cdf",()),
 ("interTxTypeSet3","Default_Inter_Tx_Type_Set3_Cdf",()),
 ("useObmc","Default_Use_Obmc_Cdf",()), ("interIntra","Default_Inter_Intra_Cdf",()),
 ("compRefType","Default_Comp_Ref_Type_Cdf",()), ("cflSign","Default_Cfl_Sign_Cdf",()),
 ("uniCompRef","Default_Uni_Comp_Ref_Cdf",()), ("wedgeInterIntra","Default_Wedge_Inter_Intra_Cdf",()),
 ("compGroupIdx","Default_Comp_Group_Idx_Cdf",()), ("compoundIdx","Default_Compound_Idx_Cdf",()),
 ("compoundType","Default_Compound_Type_Cdf",()), ("interIntraMode","Default_Inter_Intra_Mode_Cdf",()),
 ("wedgeIndex","Default_Wedge_Index_Cdf",()), ("cflAlpha","Default_Cfl_Alpha_Cdf",()),
 ("useWiener","Default_Use_Wiener_Cdf",()), ("useSgrproj","Default_Use_Sgrproj_Cdf",()),
 ("restorationType","Default_Restoration_Type_Cdf",()),
]
COEF = [
 ("txbSkip","Default_Txb_Skip_Cdf"), ("eobPt16","Default_Eob_Pt_16_Cdf"), ("eobPt32","Default_Eob_Pt_32_Cdf"),
 ("eobPt64","Default_Eob_Pt_64_Cdf"), ("eobPt128","Default_Eob_Pt_128_Cdf"), ("eobPt256","Default_Eob_Pt_256_Cdf"),
 ("eobPt512","Default_Eob_Pt_512_Cdf"), ("eobPt1024","Default_Eob_Pt_1024_Cdf"), ("eobExtra","Default_Eob_Extra_Cdf"),
 ("dcSign","Default_Dc_Sign_Cdf"), ("coeffBaseEob","Default_Coeff_Base_Eob_Cdf"),
 ("coeffBase","Default_Coeff_Base_Cdf"), ("coeffBr","Default_Coeff_Br_Cdf"),
]

out = ["// Code generated by gen_cdf.py. DO NOT EDIT.\n",
       "// CDF context layout follows the CDF arrays listed in sections 6.8.2 (init_non_coeff_cdfs, init_coeff_cdfs)\n",
       "// of the AV1 specification. Shapes are taken from the default tables.\n\n", "package av1\n\n",
       "type cdfCtx struct {\n"]
fields = []
for f, spec, rep in NONCOEF:
    sh = S.shape(S.table(spec))
    fields.append((f, spec, rep, sh, False))
for f, spec in COEF:
    sh = S.shape(S.table(spec))[1:]
    fields.append((f, spec, (), sh, True))
def typ(rep, sh): return "".join("[%d]" % d for d in rep + sh) + "uint16"
for f, spec, rep, sh, coef in fields:
    out.append("\t%s %s\n" % (f, typ(rep, sh)))
out.append("}\n\n")

out.append("func (c *cdfCtx) initNonCoeff() {\n")
for f, spec, rep, sh, coef in fields:
    if coef: continue
    dn = goname(spec)
    if not rep:
        out.append("\tc.%s = %s\n" % (f, dn))
    else:
        idx = ""
        loops = ""
        for k, d in enumerate(rep):
            loops += "\tfor i%d := 0; i%d < %d; i%d++ {\n" % (k, k, d, k)
            idx += "[i%d]" % k
        out.append(loops + "\t\tc.%s%s = %s\n" % (f, idx, dn) + "\t}\n" * len(rep))
out.append("}\n\n")

out.append("func (c *cdfCtx) initCoeff(baseQIdx int) {\n\tidx := 3\n\tswitch {\n\tcase baseQIdx <= 20:\n\t\tidx = 0\n\tcase baseQIdx <= 60:\n\t\tidx = 1\n\tcase baseQIdx <= 120:\n\t\tidx = 2\n\t}\n")
for f, spec, rep, sh, coef in fields:
    if coef:
        out.append("\tc.%s = %s[idx]\n" % (f, goname(spec)))
out.append("}\n\n")

out.append("// clearCounters zeroes the adaptation counter (last element) of every CDF.\nfunc (c *cdfCtx) clearCounters() {\n")
for f, spec, rep, sh, coef in fields:
    dims = rep + sh
    n = len(dims) - 1  # last dim is the cdf
    ix = ""
    loops = ""
    for k in range(n):
        loops += "\t" * (k + 1) + "for i%d := range c.%s%s {\n" % (k, f, ix)
        ix += "[i%d]" % k
    out.append(loops + "\t" * (n + 1) + "c.%s%s[%d] = 0\n" % (f, ix, dims[-1] - 1) + "".join("\t" * (n - k) + "}\n" for k in range(n)))
out.append("}\n")
open(OUT, "w").write("".join(out))
print("wrote", OUT, len(fields), "fields")
