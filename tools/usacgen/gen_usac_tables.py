#!/usr/bin/env python3
"""Extract the USAC constant tables from the FFmpeg 8.1 source tree and emit
Go files for internal/media.

Usage:
    python3 -I gen_usac_tables.py <ffmpeg-8.1 source dir> <internal/media dir>

The tables are parsed from the C source text (initialisers of plain
`const <type> name[dim]... = { ... };` arrays), not retyped. The output files
carry a provenance header; FFmpeg's libavcodec is licensed under the
LGPL-2.1-or-later and the repository owner accepted this (see NOTICE).

Every table is range-checked against its Go element type, and the flattened
element count is compared with the declared dimensions.
"""
import os
import re
import sys

SRC = sys.argv[1]
OUT = sys.argv[2]

HEADER = """// Code generated by tools/usacgen/gen_usac_tables.py from FFmpeg 8.1 ({files}). DO NOT EDIT.
//
// PROVENANCE AND LICENSE: the constant tables below were extracted by script
// from the source text of FFmpeg's libavcodec (aac/aacdec_tab.c, aactab.c),
// which is licensed under the GNU Lesser General Public License, version 2.1
// or later. The repository owner reviewed and accepted this licensing (see
// NOTICE).

package media
"""


def strip_comments(s):
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    s = re.sub(r'//[^\n]*', '', s)
    return s


def find_array(src, name):
    """Return (dims, flat_values) of array `name`."""
    m = re.search(r'\b' + re.escape(name) + r'((?:\s*\[[^\]]*\])+)\s*=\s*\{', src)
    if not m:
        raise SystemExit('array %s not found' % name)
    dims_txt = re.findall(r'\[([^\]]*)\]', m.group(1))
    # body: balanced braces
    i = m.end() - 1
    depth = 0
    j = i
    while True:
        c = src[j]
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                break
        j += 1
    body = src[i:j + 1]
    toks = re.findall(r'[-+]?(?:0[xX][0-9a-fA-F]+|\d+\.\d*(?:[eE][-+]?\d+)?f?|\d+[eE][-+]?\d+f?|\d+)', body.replace('{', ' ').replace('}', ' '))
    vals = []
    for t in toks:
        t = t.rstrip('f')
        if t.lower().startswith(('0x', '-0x', '+0x')):
            vals.append(int(t, 16))
        elif '.' in t or 'e' in t.lower():
            vals.append(float(t))
        else:
            vals.append(int(t))
    return dims_txt, vals


RANGES = {
    'uint8': (0, 255), 'int8': (-128, 127), 'uint16': (0, 65535), 'int16': (-32768, 32767),
    'uint32': (0, 2**32 - 1), 'int32': (-2**31, 2**31 - 1), 'int': (-2**31, 2**31 - 1),
}


def emit(f, goname, gotype, dims, vals, doc, per_line=12):
    isf = gotype.startswith('float')
    if not isf:
        lo, hi = RANGES[gotype]
        for v in vals:
            assert lo <= v <= hi, (goname, v)
    f.write('\n// %s\n' % doc)
    f.write('var %s = [...]%s{\n' % (goname, gotype))
    for k in range(0, len(vals), per_line):
        chunk = vals[k:k + per_line]
        if isf:
            f.write('\t' + ', '.join(repr(float(v)) for v in chunk) + ',\n')
        elif gotype.startswith('uint') and max(chunk) > 255:
            f.write('\t' + ', '.join(str(v) for v in chunk) + ',\n')
        else:
            f.write('\t' + ', '.join(str(v) for v in chunk) + ',\n')
    f.write('}\n')


def main():
    lib = os.path.join(SRC, 'libavcodec')
    aactab = strip_comments(open(os.path.join(lib, 'aactab.c')).read())
    aadtab = strip_comments(open(os.path.join(lib, 'aac', 'aacdec_tab.c')).read())

    # --- arithmetic coder and misc FD tables ------------------------------
    jobs = [
        (aactab, 'ff_aac_ac_msb_cdfs', 'usacAcMsbCdfs', 'uint16', 'context-based arithmetic coder MSB cumulative frequencies [64][17]'),
        (aactab, 'ff_aac_ac_lsb_cdfs', 'usacAcLsbCdfs', 'uint16', 'arithmetic coder LSB cumulative frequencies [3][4]'),
        (aactab, 'ff_aac_ac_lookup_m', 'usacAcLookupM', 'uint8', 'arithmetic coder context lookup (742)'),
        (aactab, 'ff_aac_ac_hash_m', 'usacAcHashM', 'uint32', 'arithmetic coder context hash (742): hash<<8 | pki'),
        (aactab, 'ff_aac_usac_mdst_filt_cur', 'usacMdstFilt', 'float32', 'complex prediction MDST filter coefficients [4 window][4 shape][7]'),
    ]
    with open(os.path.join(OUT, 'usac_tables_gen.go'), 'w') as f:
        f.write(HEADER.format(files='aactab.c'))
        for src, cname, goname, gotype, doc in jobs:
            dims, vals = find_array(src, cname)
            emit(f, goname, gotype, dims, vals, doc, 8 if gotype != 'uint32' else 6)
        # expected sizes
        f.write('\nconst (\n\tusacAcMsbN = 64\n\tusacAcLookupN = 742\n)\n')


main()
