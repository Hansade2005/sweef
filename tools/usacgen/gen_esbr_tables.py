#!/usr/bin/env python3
"""Extract the constant tables of the USAC eSBR decoder from the libxaac source
tree and emit internal/media/esbr_tables_gen.go.

Usage:
    python3 -I gen_esbr_tables.py <libxaac source dir> <internal/media dir>

libxaac (Ittiam Systems, https://github.com/ittiam-systems/libxaac) is
licensed under the Apache License 2.0. The tables are plain constant data of
ISO/IEC 23003-3 (QMF prototype windows, random phase and noise tables, filter
coefficients); they are parsed from the C source text, not retyped.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from usacgen_common import (strip_comments, find_array, find_after_comment,  # noqa: E402
                            find_struct_init, find_exprs, emit)

SRC = sys.argv[1]
OUT = sys.argv[2]

HEADER = """// Code generated by tools/usacgen/gen_esbr_tables.py from libxaac ({files}). DO NOT EDIT.
//
// PROVENANCE AND LICENSE: the constant tables below were extracted by script
// from the source text of libxaac (https://github.com/ittiam-systems/libxaac,
// Copyright (C) 2015, 2018, 2023 The Android Open Source Project, originally developed and
// contributed by Ittiam Systems Pvt. Ltd, Bangalore), which is licensed under
// the Apache License, Version 2.0 (http://www.apache.org/licenses/LICENSE-2.0).
// See NOTICE.

package media
"""


def raw(path):
    return open(os.path.join(SRC, path)).read()


def main():
    files = ['common/ixheaac_esbr_rom.c', 'decoder/ixheaacd_sbr_rom.c',
             'decoder/ixheaacd_common_rom.c', 'decoder/ixheaacd_sbrdec_lpfuncs.c',
             'decoder/ixheaacd_pvc_rom.c']
    rom = strip_comments(raw(files[0]))
    sbrrom = raw(files[1])
    common = raw(files[2])
    lpf = strip_comments(raw(files[3]))
    pvc = strip_comments(raw(files[4]))
    out = open(os.path.join(OUT, 'esbr_tables_gen.go'), 'w')
    out.write(HEADER.format(files=', '.join(files)))

    d, v = find_array(rom, 'ixheaac_random_phase')
    emit(out, 'esbrRandomPhase', 'float32', d, v, 'noise phase vectors (real, imag), 512 entries', 6)
    d, v = find_array(rom, 'ixheaac_g_lim_gains')
    emit(out, 'esbrLimGains', 'float32', d, v, 'limiter gain values', 4)
    d, v = find_array(rom, 'ixheaac_q_gamma_table')
    emit(out, 'esbrQGamma', 'float32', d, v, 'inter-TES gamma values', 4)
    v = find_struct_init(rom.replace('ixheaac_hphase_tbl[2][8]', 'ixheaac_hphase_tbl'), 'ixheaac_hphase_tbl')
    assert len(v) == 8
    emit(out, 'esbrHPhase', 'float32', ['2', '4'], v, 'harmonic phase tables [re/im][harm_index]', 4)
    for i in range(5):
        v = find_struct_init(rom, 'ixheaac_fir_%d' % i)
        assert len(v) == i + 1
        emit(out, 'esbrFir%d' % i, 'float32', [str(i + 1)], v, 'smoothing filter of length %d' % (i + 1), 8)
    d, v = find_array(lpf, 'ixheaacd_new_bw_table')
    emit(out, 'esbrNewBw', 'float32', d, v, 'chirp factors [prev inverse filtering mode][mode]', 4)
    v = find_after_comment(common, 'const WORD16 log_dual_is_table[LOG_2_TABLE_SIZE]', 65)
    emit(out, 'esbrLogDual', 'int16', ['65'], v, 'log2 table, Q12 (index 0: most negative value)', 9)
    v = find_after_comment(sbrrom, 'WORD32 esbr_qmf_c[1280]', 1280)
    emit(out, 'esbrQmfC', 'int32', ['1280'], v, 'eSBR analysis window of the 32 and 16 band banks, Q31', 8)
    v = find_after_comment(sbrrom, 'WORD32 esbr_qmf_c_24[480]', 480)
    emit(out, 'esbrQmfC24', 'int32', ['480'], v, 'eSBR analysis window of the 24 band bank, Q31', 8)

    # harmonic bandwidth extension (HBE) transposer tables
    hbe = [
        ('ixheaac_sub_samp_qmf_window_coeff', 'esbrSubSampWin', 'float32', 'prototype windows of the HBE sub-sampled QMF banks (lengths 4, 8, 12, 16, 20, 24, 32, 40, ...)', 8),
        ('ixheaac_start_subband2kL_tbl', 'esbrStartSubband2kL', 'int32', 'HBE start subband to k_start mapping', 11),
        ('ixheaac_cos_table_trans_qmf', 'esbrCosTableTransQmf', 'float32', 'HBE synthesis modulation, [7][32*2]', 8),
        ('ixheaac_phase_vocoder_cos_table', 'esbrPhaseVocoderCos', 'float32', 'HBE phase rotation, cosine', 8),
        ('ixheaac_phase_vocoder_sin_table', 'esbrPhaseVocoderSin', 'float32', 'HBE phase rotation, sine', 8),
        ('ixheaac_hbe_post_anal_proc_interp_coeff', 'esbrHbeInterpCoeff', 'float32', 'HBE interpolation coefficients [4][2]', 8),
        ('ixheaac_hbe_x_prod_cos_table_trans_2', 'esbrHbeXProdCos2', 'float32', 'HBE cross product rotation, transposition factor 2', 8),
        ('ixheaac_hbe_x_prod_cos_table_trans_3', 'esbrHbeXProdCos3', 'float32', 'HBE cross product rotation, transposition factor 3', 8),
        ('ixheaac_hbe_x_prod_cos_table_trans_4', 'esbrHbeXProdCos4', 'float32', 'HBE cross product rotation, transposition factor 4', 8),
        ('ixheaac_hbe_x_prod_cos_table_trans_4_1', 'esbrHbeXProdCos41', 'float32', 'HBE cross product rotation, transposition factor 4 (d2 == 1)', 8),
        ('ixheaac_synth_cos_table_kl_4', 'esbrSynthCosKL4', 'float32', 'HBE synthesis twiddles, 4 channels', 8),
        ('ixheaac_synth_cos_table_kl_8', 'esbrSynthCosKL8', 'float32', 'HBE synthesis twiddles, 8 channels', 8),
        ('ixheaac_synth_cos_table_kl_12', 'esbrSynthCosKL12', 'float32', 'HBE synthesis twiddles, 12 channels', 8),
        ('ixheaac_synth_cos_table_kl_16', 'esbrSynthCosKL16', 'float32', 'HBE synthesis twiddles, 16 channels', 8),
        ('ixheaac_synth_cos_table_kl_20', 'esbrSynthCosKL20', 'float32', 'HBE synthesis matrix, 20 channels', 8),
        ('ixheaac_analy_cos_sin_table_kl_8', 'esbrAnalyCosSinKL8', 'float32', 'HBE analysis twiddles, 8 channels', 8),
        ('ixheaac_analy_cos_sin_table_kl_16', 'esbrAnalyCosSinKL16', 'float32', 'HBE analysis twiddles, 16 channels', 8),
        ('ixheaac_analy_cos_sin_table_kl_24', 'esbrAnalyCosSinKL24', 'float32', 'HBE analysis twiddles, 24 channels', 8),
        ('ixheaac_analy_cos_sin_table_kl_32', 'esbrAnalyCosSinKL32', 'float32', 'HBE analysis twiddles, 32 channels', 8),
        ('ixheaac_analy_cos_sin_table_kl_40', 'esbrAnalyCosSinKL40', 'float32', 'HBE analysis matrix, 40 channels', 8),
        ('ixheaac_sel_case', 'esbrSelCase', 'float32', 'HBE interpolation selection coefficients [5][8]', 8),
    ]
    for cname, goname, gotype, doc, per in hbe:
        d, v = find_array(rom, cname)
        emit(out, goname, gotype, d, v, doc, per)

    # predictive vector coding (PVC) tables
    pvct = [
        ('ixheaacd_pvc_smoothing_wind_tab_ns4', 'esbrPvcSmoothNs4', 'float32', 'PVC time smoothing window, 4 slots', 4),
        ('ixheaacd_pvc_smoothing_wind_tab_ns16', 'esbrPvcSmoothNs16', 'float32', 'PVC time smoothing window, 16 slots', 4),
        ('ixheaacd_pvc_smoothing_wind_tab_ns3', 'esbrPvcSmoothNs3', 'float32', 'PVC time smoothing window, 3 slots', 4),
        ('ixheaacd_pvc_smoothing_wind_tab_ns12', 'esbrPvcSmoothNs12', 'float32', 'PVC time smoothing window, 12 slots', 4),
        ('ixheaacd_pred_coeff_pvc_id_boundaries_1', 'esbrPvcIDBound1', 'uint8', 'PVC mode 1 prediction table group boundaries', 8),
        ('ixheaacd_q_factor_table_mode_1', 'esbrPvcQFac1', 'float32', 'PVC mode 1 quantisation factors', 4),
        ('ixheaacd_pred_coeff_table_1_mode_1', 'esbrPvcPred1Mode1', 'uint8', 'PVC mode 1 prediction coefficients [3][3][8] (signed bytes)', 12),
        ('ixheaacd_pred_coeff_table_2_mode_1', 'esbrPvcPred2Mode1', 'uint8', 'PVC mode 1 prediction offsets [128][8] (signed bytes)', 16),
        ('ixheaacd_pred_coeff_pvc_id_boundaries_2', 'esbrPvcIDBound2', 'uint8', 'PVC mode 2 prediction table group boundaries', 8),
        ('ixheaacd_q_factor_table_mode_2', 'esbrPvcQFac2', 'float32', 'PVC mode 2 quantisation factors', 4),
        ('ixheaacd_pred_coeff_table_1_mode_2', 'esbrPvcPred1Mode2', 'uint8', 'PVC mode 2 prediction coefficients [3][3][6] (signed bytes)', 12),
        ('ixheaacd_pred_coeff_table_2_mode_2', 'esbrPvcPred2Mode2', 'uint8', 'PVC mode 2 prediction offsets [128][6] (signed bytes)', 12),
    ]
    for cname, goname, gotype, doc, per in pvct:
        if 'q_factor' in cname:
            v = find_exprs(pvc, cname)
            d = ['4']
        else:
            d, v = find_array(pvc, cname)
        emit(out, goname, gotype, d, v, doc, per)
    out.close()


main()
