#!/usr/bin/env python3
"""Extract the constant tables of the USAC MPEG Surround (MPS212) decoder from
the libxaac source tree and emit internal/media/mps_tables_gen.go.

Usage:
    python3 -I gen_mps_tables.py <libxaac source dir> <internal/media dir>

libxaac (Ittiam Systems, https://github.com/ittiam-systems/libxaac) is
licensed under the Apache License 2.0. The tables are constant data of
ISO/IEC 23003-1 / 23003-3 (Huffman trees, dequantisation, upmix weights,
hybrid and polyphase filters, decorrelator lattice filters); they are parsed
from the C source text, not retyped.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from usacgen_common import strip_comments, find_array, find_struct_init, emit  # noqa: E402

SRC = sys.argv[1]
OUT = sys.argv[2]

HEADER = """// Code generated by tools/usacgen/gen_mps_tables.py from libxaac ({files}). DO NOT EDIT.
//
// PROVENANCE AND LICENSE: the constant tables below were extracted by script
// from the source text of libxaac (https://github.com/ittiam-systems/libxaac,
// Copyright (C) 2015, 2018, 2023 The Android Open Source Project, originally developed and
// contributed by Ittiam Systems Pvt. Ltd, Bangalore), which is licensed under
// the Apache License, Version 2.0 (http://www.apache.org/licenses/LICENSE-2.0).
// See NOTICE.

package media
"""


def raw(path):
    return strip_comments(open(os.path.join(SRC, path)).read())


def main():
    files = ['decoder/ixheaacd_mps_rom.c', 'decoder/ixheaacd_mps_parse.c',
             'decoder/ixheaacd_mps_decorr.c']
    rom = raw(files[0])
    parse = raw(files[1])
    decor = raw(files[2])
    out = open(os.path.join(OUT, 'mps_tables_gen.go'), 'w')
    out.write(HEADER.format(files=', '.join(files)))

    # Huffman trees: [type][table][node][2]
    v = find_struct_init(rom, 'ixheaacd_huff_cld_nodes')
    n1 = 3 * 30 * 2
    n2 = 3 * 2 * (15 + 35 + 63 + 99) * 2
    assert len(v) == n1 + n2, len(v)
    emit(out, 'mpsHuffCld1D', 'int16', ['3', '30', '2'], v[:n1], 'CLD 1-D Huffman trees [diff type][node][bit]', 16)
    emit(out, 'mpsHuffCld2D', 'int16', ['3', '2', '212', '2'], v[n1:],
         'CLD 2-D Huffman trees [diff type][pairing][lav3 (15), lav5 (35), lav7 (63), lav9 (99) nodes][bit]', 16)
    v = find_struct_init(rom, 'ixheaacd_huff_icc_nodes')
    n1 = 3 * 7 * 2
    n2 = 3 * 2 * (3 + 15 + 35 + 63) * 2
    assert len(v) == n1 + n2, len(v)
    emit(out, 'mpsHuffIcc1D', 'int16', ['3', '7', '2'], v[:n1], 'ICC 1-D Huffman trees [diff type][node][bit]', 16)
    emit(out, 'mpsHuffIcc2D', 'int16', ['3', '2', '116', '2'], v[n1:],
         'ICC 2-D Huffman trees [diff type][pairing][lav1 (3), lav3 (15), lav5 (35), lav7 (63) nodes][bit]', 16)
    v = find_struct_init(rom, 'ixheaacd_huff_part0_nodes')
    assert len(v) == 30 * 2 + 7 * 2 + 25 * 2, len(v)
    emit(out, 'mpsHuffPart0Cld', 'int16', ['30', '2'], v[:60], 'CLD first band Huffman tree', 16)
    emit(out, 'mpsHuffPart0Icc', 'int16', ['7', '2'], v[60:74], 'ICC first band Huffman tree', 16)
    v = find_struct_init(rom, 'ixheaacd_huff_lav_idx_nodes')
    assert len(v) == 6
    emit(out, 'mpsHuffLav', 'int16', ['3', '2'], v, 'largest absolute value index Huffman tree', 16)

    # upmix weights, ICC index 0..7, CLD index 0..30. Only the IPD index 0
    # plane is used (phase coding is not supported).
    for cname, goname, doc in [
            ('ixheaacd_weight', 'mpsWeight', 'prediction upmix weight [icc][cld] (ipd index 0)'),
            ('ixheaacd_re_weight', 'mpsReWeight', 'prediction upmix real weight [icc][cld] (ipd index 0)'),
            ('ixheaacd_im_weight', 'mpsImWeight', 'prediction upmix imaginary weight [icc][cld] (ipd index 0)'),
            ('ixheaacd_beta', 'mpsBeta', 'prediction upmix decorrelator weight [icc][cld] (ipd index 0)')]:
        d, v = find_array(rom, cname)
        assert len(v) == 16 * 8 * 31
        emit(out, goname, 'float32', ['8', '31'], v[:8 * 31], doc, 8)
    d, v = find_array(rom, 'ixheaacd_c_l_table')
    emit(out, 'mpsCL', 'float32', d, v, 'channel level difference gains [cld]', 8)
    d, v = find_array(rom, 'ixheaacd_cos_table')
    emit(out, 'mpsCos', 'float32', ['8', '31'], v, 'OTT upmix cosine [icc][cld]', 8)
    d, v = find_array(rom, 'ixheaacd_sin_table')
    emit(out, 'mpsSin', 'float32', ['8', '31'], v, 'OTT upmix sine [icc][cld]', 8)

    # QMF synthesis and hybrid analysis
    d, v = find_array(rom, 'ixheaacd_mps_polyphase_filter_coeff')
    assert len(v) == 640
    emit(out, 'mpsPolyphase', 'float32', ['640'], v, 'synthesis polyphase window', 8)
    d, v = find_array(rom, 'ixheaacd_mps_post_twid')
    emit(out, 'mpsPostTwid', 'float32', d, v, 'synthesis post twiddle', 8)
    d, v = find_array(rom, 'ixheaacd_mps_pre_twid')
    emit(out, 'mpsPreTwid', 'float32', d, v, 'synthesis pre twiddle', 8)
    d, v = find_array(rom, 'ixheaacd_ia_mps_hyb_filter_coeff_8')
    emit(out, 'mpsHybFilt8', 'float32', ['13'], v, 'hybrid filter, 8 sub-band split of QMF band 0', 8)
    d, v = find_array(rom, 'ixheaacd_mps_hyb_filter_coeff_2')
    emit(out, 'mpsHybFilt2', 'float32', ['13'], v, 'hybrid filter, 2 sub-band split of QMF bands 1 and 2', 8)
    d, v = find_array(rom, 'ixheaacd_sine')
    emit(out, 'mpsHybSine', 'float32', ['8', '8'], v, 'hybrid filter sine table (columns 1..4 are used)', 8)
    d, v = find_array(rom, 'ixheaacd_cosine')
    emit(out, 'mpsHybCosine', 'float32', ['8', '8'], v, 'hybrid filter cosine table (columns 1..3 are used)', 8)
    d, v = find_array(rom, 'ixheaacd_mps_gain_set_indx')
    emit(out, 'mpsGainSetIdx', 'int32', d, v, 'first hybrid band of a residual band count', 10)

    # parameter band mappings
    for n in (4, 5, 7, 10, 14, 20, 28):
        d, v = find_array(parse, 'ixheaacd_hybrid_band_71_to_processing_band_%d_map' % n)
        assert len(v) == 71
        emit(out, 'mpsHybBand%d' % n, 'uint8', ['71'], v, 'hybrid band to parameter band map, %d bands' % n, 24)
    d, v = find_array(parse, 'ixheaacd_mps_clip_gain_table')
    emit(out, 'mpsClipGain', 'float32', d, v, 'fixed downmix gains', 8)
    d, v = find_array(parse, 'ixheaacd_cld_de_quant_table')
    emit(out, 'mpsCLDDequant', 'float32', d, v, 'CLD dequantisation (dB)', 8)
    d, v = find_array(parse, 'ixheaacd_icc_de_quant_table')
    emit(out, 'mpsICCDequant', 'float32', d, v, 'ICC dequantisation', 8)

    # decorrelator
    for i in range(4):
        d, v = find_array(decor, 'ixheaacd_lattice_coeff_%d_filt_num_coeff' % i)
        emit(out, 'mpsDecorNum%d' % i, 'float32', d, v, 'decorrelator all-pass numerator, band %d' % i, 8)
        d, v = find_array(decor, 'ixheaacd_lattice_coeff_%d_filt_den_coeff' % i)
        emit(out, 'mpsDecorDen%d' % i, 'float32', d, v, 'decorrelator all-pass denominator, band %d' % i, 8)
    d, v = find_array(decor, 'ixheaacd_decorr_delay')
    emit(out, 'mpsDecorDelay', 'int32', d, v, 'decorrelator delays', 8)
    for i in range(3):
        d, v = find_array(decor, 'ixheaacd_qmf_split_freq_%d' % i)
        emit(out, 'mpsSplitFreq%d' % i, 'int32', d, v, 'decorrelator split frequencies, config %d' % i, 8)
    d, v = find_array(decor, 'ixheaacd_hybrid_to_qmf_map')
    emit(out, 'mpsHybToQMF', 'uint8', ['71'], v, 'hybrid band to QMF band map', 24)
    out.close()


main()
