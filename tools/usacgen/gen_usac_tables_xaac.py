#!/usr/bin/env python3
"""Extract USAC constant tables that FFmpeg does not contain (it has no LPD,
eSBR harmonic transposer or MPS212 synthesis) from the libxaac source tree and
emit internal/media/usac_tables_xaac_gen.go.

Usage:
    python3 -I gen_usac_tables_xaac.py <libxaac source dir> <internal/media dir>

libxaac (Ittiam Systems, https://github.com/ittiam-systems/libxaac) is
licensed under the Apache License 2.0. The tables are plain constant data of
ISO/IEC 23003-3 (filter coefficients, codebooks); they are parsed from the C
source text, not retyped. Provenance and the licence are recorded in the
generated file and in NOTICE. Everything generated here lives in separate
files so that it can be replaced by tables from another source.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from usacgen_common import strip_comments, find_array, emit  # noqa: E402

SRC = sys.argv[1]
OUT = sys.argv[2]

HEADER = """// Code generated by tools/usacgen/gen_usac_tables_xaac.py from libxaac ({files}). DO NOT EDIT.
//
// PROVENANCE AND LICENSE: the constant tables below were extracted by script
// from the source text of libxaac (https://github.com/ittiam-systems/libxaac,
// Copyright (C) 2018 The Android Open Source Project, originally developed and
// contributed by Ittiam Systems Pvt. Ltd, Bangalore), which is licensed under
// the Apache License, Version 2.0 (http://www.apache.org/licenses/LICENSE-2.0).
// See NOTICE.

package media
"""


def read(path):
    return strip_comments(open(os.path.join(SRC, path)).read())


def main():
    ext = read('decoder/ixheaacd_ext_ch_ele.c')
    out = open(os.path.join(OUT, 'usac_tables_xaac_gen.go'), 'w')
    out.write(HEADER.format(files='decoder/ixheaacd_ext_ch_ele.c'))
    # MDST filter coefficients of the complex stereo prediction (Q15)
    names = [
        ('long_sin', 'longsin'), ('long_kbd', 'longkbd'), ('long_sin_kbd', 'longsinkbd'), ('long_kbd_sin', 'longkbdsin'),
        ('start_sin', 'startsin'), ('start_kbd', 'startkbd'), ('start_sin_kbd', 'startsinkbd'), ('start_kbd_sin', 'startkbdsin'),
        ('stop_sin', 'stopsin'), ('stop_kbd', 'stopkbd'), ('stop_sin_kbd', 'stopsinkbd'), ('stop_kbd_sin', 'stopkbdsin'),
        ('stopstart_sin', 'stopstartsin'), ('stopstart_kbd', 'stopstartkbd'),
        ('stopstart_sin_kbd', 'stopstartsinkbd'), ('stopstart_kbd_sin', 'stopstartkbdsin'),
        ('l_s_start_left_sin', 'lsstartleftsin'), ('l_s_start_left_kbd', 'lsstartleftkbd'),
        ('stop_stopstart_left_sin', 'stopstopstartleftsin'), ('stop_stopstart_left_kbd', 'stopstopstartleftkbd'),
    ]
    for cn, gn in names:
        dims, vals = find_array(ext, 'ixheaacd_mdst_fcoeff_' + cn)
        assert len(vals) == 7, cn
        emit(out, 'usacMdstQ15_' + gn, 'int16', dims, vals, 'MDST filter coefficients %s, Q15, filter[j] multiplies line k-3+j' % cn, 7)
    out.close()


main()
