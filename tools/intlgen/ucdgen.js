#!/usr/bin/env node
// ucdgen: Unicode Character Database -> internal/intl/segment/tables.go (the property tables UAX #29 needs).
//
//   curl -O https://www.unicode.org/Public/16.0.0/ucd/auxiliary/{Grapheme,Word,Sentence}BreakProperty.txt
//   curl -O https://www.unicode.org/Public/16.0.0/ucd/emoji/emoji-data.txt
//   curl -O https://www.unicode.org/Public/16.0.0/ucd/DerivedCoreProperties.txt
//   node ucdgen.js <dir with the files> ../../internal/intl/segment/tables.go
'use strict';
const fs = require('fs'), path = require('path');
const dir = process.argv[2], out = process.argv[3];

function parse(file, want) {
  const rows = [];
  for (const line of fs.readFileSync(path.join(dir, file), 'utf8').split('\n')) {
    const m = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z_]+)(?:\s*;\s*([A-Za-z_]+))?/.exec(line);
    if (!m) continue;
    const lo = parseInt(m[1], 16), hi = m[2] ? parseInt(m[2], 16) : lo;
    rows.push([lo, hi, want === 'incb' ? (m[3] === 'InCB' ? m[4] : null) : m[3]]);
  }
  return rows.filter((r) => r[2]);
}
function table(name, rows, classes) {
  rows.sort((a, b) => a[0] - b[0]);
  // merge adjacent ranges of the same class
  const merged = [];
  for (const r of rows) {
    const last = merged[merged.length - 1];
    if (last && last[2] === r[2] && last[1] + 1 === r[0]) last[1] = r[1]; else merged.push(r.slice());
  }
  let s = `var ${name} = []rng{\n`;
  for (const [lo, hi, c] of merged) {
    if (!classes.includes(c)) throw new Error(name + ': unexpected class ' + c);
    s += `\t{0x${lo.toString(16)}, 0x${hi.toString(16)}, ${prefix[name]}${c}},\n`;
  }
  return s + '}\n\n';
}
const prefix = { gcbTable: 'gcb', wbTable: 'wb', sbTable: 'sb', incbTable: 'incb' };
const GCB = ['CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator', 'Prepend', 'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT'];
const WB = ['CR', 'LF', 'Newline', 'Extend', 'ZWJ', 'Regional_Indicator', 'Format', 'Katakana', 'Hebrew_Letter', 'ALetter', 'Single_Quote', 'Double_Quote', 'MidNumLet', 'MidLetter', 'MidNum', 'Numeric', 'ExtendNumLet', 'WSegSpace'];
const SB = ['CR', 'LF', 'Extend', 'Sep', 'Format', 'Sp', 'Lower', 'Upper', 'OLetter', 'Numeric', 'ATerm', 'SContinue', 'STerm', 'Close'];
const camel = (s) => s.replace(/_/g, '');
let go = '// Code generated by tools/intlgen/ucdgen.js from Unicode 16.0.0; DO NOT EDIT.\n\npackage segment\n\n';
for (const [n, list] of [['gcb', GCB], ['wb', WB], ['sb', SB]]) {
  go += `// ${n} property values\nconst (\n`;
  list.forEach((c, i) => { go += `\t${n}${camel(c)}${i === 0 ? ' uint8 = iota + 1' : ''}\n`; });
  go += ')\n\n';
}
go += 'const (\n\tincbConsonant uint8 = iota + 1\n\tincbLinker\n\tincbExtend\n)\n\n';
go += 'type rng struct {\n\tlo, hi rune\n\tc      uint8\n}\n\n';
const fix = (rows) => rows.map((r) => [r[0], r[1], camel(r[2])]);
const g = fix(parse('GraphemeBreakProperty.txt')), w = fix(parse('WordBreakProperty.txt')), s = fix(parse('SentenceBreakProperty.txt'));
const ib = fix(parse('DerivedCoreProperties.txt', 'incb'));
const ep = parse('emoji-data.txt').filter((r) => r[2] === 'Extended_Pictographic');
prefix.gcbTable = 'gcb'; prefix.wbTable = 'wb'; prefix.sbTable = 'sb'; prefix.incbTable = 'incb';
go += table('gcbTable', g, GCB.map(camel));
go += table('wbTable', w, WB.map(camel));
go += table('sbTable', s, SB.map(camel));
go += table('incbTable', ib, ['Consonant', 'Linker', 'Extend']);
go += 'var extPictTable = []rune{ // pairs lo, hi\n';
ep.sort((a, b) => a[0] - b[0]);
const mergedEP = [];
for (const r of ep) { const l = mergedEP[mergedEP.length - 1]; if (l && l[1] + 1 === r[0]) l[1] = r[1]; else mergedEP.push([r[0], r[1]]); }
for (const [lo, hi] of mergedEP) go += `\t0x${lo.toString(16)}, 0x${hi.toString(16)},\n`;
go += '}\n';
fs.writeFileSync(out, go);
console.log('wrote', out, go.length, 'bytes');
