func (p *rep) runQuality() {
	p.f("## Run quality\n\n")
	noisy := 0
	total := 0
	for _, n := range p.names {
		for _, it := range p.iters(n) {
			total++
			if it.Noisy {
				noisy++
			}
		}
	}
	p.f("- iterations: %d recorded, %d flagged as run on a not-quite-idle machine (>= 0.2 foreign cores for 60 s before the iteration started).\n", total, noisy)
	for _, n := range p.names {
		var st []float64
		for _, it := range p.iters(n) {
			st = append(st, it.CPUStallPct)
		}
		if len(st) > 0 {
			p.f("- %s: CPU contention during the iteration (share of time in which some runnable task waited for a CPU, machine-wide `/proc/pressure/cpu`): median %.0f%%, max %.0f%%. Run on an idle 4-core machine this is a few percent; high values mean other jobs were competing.\n", n, median(st), maxOf(st))
		}
	}
	p.f("- order: odd iterations ran Chromium first, even ones Sweef first (alternating).\n")
	for _, n := range p.names {
		cnt := map[string]int{}
		for _, it := range p.iters(n) {
			for k, v := range it.LatFail {
				cnt[k] += v
			}
		}
		var parts []string
		for k, v := range cnt {
			if v > 0 {
				parts = append(parts, fmt.Sprintf("%s %d", k, v))
			}
		}
		sort.Strings(parts)
		if len(parts) > 0 {
			p.f("- %s: missed latency samples (no pixel change within the timeout): %s.\n", n, strings.Join(parts, ", "))
		}
	}
	p.f("\n")
}

func (p *rep) method() {
	p.f(`## Method

Everything is measured from the **outside**, the same way for both browsers, with nothing inside either browser instrumented.

- **Display.** A new Xvfb (%s) is started for every measured launch: 1920x1080x24, no compositor, no window manager. The window is 1280x800 in both.
- **Observer and driver.** A small X11 client written for this harness (bench/vschrome/x11.go; same protocol approach as the XTEST/GetImage helpers in internal/shell/x11's tests) uses two connections: one injects input with the XTEST extension, one reads pixels with GetImage of the root window and listens for DAMAGE events. All timestamps come from one monotonic clock in one process.
- **Input latency.** Timestamp taken immediately before the XTEST key-down request is written; stop at the first DAMAGE event inside the region whose read-back pixels differ from the baseline read just before the key. Before every key the harness waits for 60 ms (omnibox) / 300 ms (tab actions) without damage in the region, so a late paint of the previous key is not blamed on the next one. For the "dropdown closed" trials the key is sent right after a caret blink so a blink cannot be mistaken for the response. Keys are held 45 ms, then released; 80–230 ms between characters; the same seeded sequence of gaps for both browsers.
- **Regions.** Omnibox plus the area its dropdown opens into (per browser, because the layouts differ: Chromium x 108–1152, Sweef x 246–1036, y 36–260 in window coordinates). Tab switch and new tab: the whole window ("first visible change"), and separately the page area.
- **Memory.** Process tree = every process whose environment has the run's unique tag (children inherit it, including re-parented helpers). PSS and RSS from /proc/PID/smaps_rollup.
- **Idle CPU.** utime+stime from /proc/PID/stat, sampled every second for every tagged process, deltas per process.
- **Start-up.** exec to first frame with the UI painted, from DAMAGE events on the root window plus a read-back of the top band; "new-tab page ready" = page area non-blank and unchanged for 700 ms. Cold file cache = `+"`echo 3 > /proc/sys/vm/drop_caches`"+` before the launch.
- **Page load.** Enter key-down to first non-blank content frame / load event (a script in the fixture pages reports to the server: `+"`XMLHttpRequest`"+`, because Sweef does not fetch detached `+"`new Image()`"+` beacons) / last visual change. Wire bytes by an independent counter (fixture-socket counter for local pages, the recording proxy of bench/datasaver for real pages).
- **Pages.** A local server (127.0.0.1) with fixed, seeded content: a ~100 KB text article, a heavy page (12 generated JPEG/PNG images, 3 scripts doing a prime sieve, 400 DOM nodes and a 30 000 element sort, a stylesheet), an SPA-like page (60 KB script rendering 240 cards from a JSON API, hash routing). `+"`Cache-Control: no-store`"+`, no compression. Real pages come from bench/datasaver/sites.txt through the sandbox proxy.
- **Fairness.** Same window size, same Xvfb flags, a fresh profile and a fresh X server for every launch, browsers' order alternated per iteration, a recording proxy in front of both, Chromium's background networking disabled (that removes Chromium work, which can only help Chromium on the idle-CPU and start-up rows) and its network search suggestions disabled through a pre-seeded profile preference (they repaint the dropdown at a time unrelated to the key that triggered them; Sweef's omnibox makes no such request, and with them on a real Chromium does extra work per key). Sweef's profile is pre-seeded with `+"`onboarding.done=true`"+` (otherwise its first tab is the onboarding page); Chromium runs with `+"`--no-first-run`"+`. The machine is checked for idleness before every iteration and the load is recorded.
- **Statistics.** Medians with min and max over runs for per-run quantities; pooled nearest-rank percentiles for latency samples; no outlier removal. N = %d runs per browser.
- **Completeness gate.** This document prints verdicts only when every iteration of both browsers finished every phase (startup x3, memory x2, idle CPU, all latency series with at most 5%% missing samples, all page loads) and the run is not a smoke run.

Re-run: `+"`scripts/bench/vschrome.sh`"+` (builds Sweef from `+"`git archive HEAD`"+` by default, runs, writes `+"`bench/vschrome/results/<label>.json`"+` and regenerates this file).

`, p.r.Meta.XvfbArgs, p.r.Meta.Runs)
}

func (p *rep) caveats() {
	p.b.WriteString(`## Weaknesses of the method

- **Xvfb is not a desktop.** Frames are software-composited and copied into the X server's framebuffer; no GPU, no compositor, no vsync. Chromium's GPU process runs a software GL path here, which a user with a GPU would not have, and its raster/compositing threads compete for four cores. Absolute latencies are not what a real desktop shows; only the comparison is meaningful, and even it could change with a GPU (Chromium would gain more than Sweef's CPU renderer).
- **"First changed pixel" is not "the final frame".** Both browsers may paint an intermediate state first (Chromium can draw the omnibox text before the dropdown rows; a tab strip highlight can precede page content). The harness reports the first change in the region and, for tab switch and new tab, separately the first change in the page area. A browser that paints early and then repaints looks better here than one that paints once, completely.
- **Regions differ per browser** (layouts differ) and were fixed from screenshots, not discovered; a change of either UI layout needs the numbers in phases.go updated.
- **Caret blink.** Handled by timing the key right after a toggle; if a browser's blink period is not 500 ms the guard is imperfect and a few early samples are possible.
- **Real pages** depend on the network, on third-party content that changes, and on each browser being served different markup (user agent). Their time series are noisier and a page that animates never "settles" (capped at 40 s). They were loaded through a recording proxy that re-tunnels to the sandbox's egress proxy, which adds a constant hop for both browsers.
- **Load event for real pages is not measured** (no beacon possible from outside); "visually settled" is a proxy, and a page that paints its final content early and then fiddles with an ad slot looks late.
- **One machine, 4 shared cores, other engineers' jobs.** Idleness is checked and recorded, not guaranteed; the run-quality section counts how often it was not quiet.
- **Memory** is whole-tree PSS at a fixed settle time, on fixture pages; it says nothing about 100-tab sessions, long-running leaks, or sites with video/WebGL. PSS divides shared pages by the sharers that exist in this tree only; Chromium's zygote sharing across renderers is handled by PSS, but the page cache of the browser binary itself is not charged to either.
- **Chromium flags.** ` + "`--no-sandbox`" + ` (required as root in a container) removes the sandbox's cost from Chromium's tree: a normal Chromium has a little more overhead. Background networking, component update and sync are off. The Playwright build is Chromium 141, not the build that ships as Chrome.
- **Disk.** Playwright's directory is not an installer package; compression ratios of a .deb or the official Chrome tarball would differ.
- **Sweef bug-for-bug.** The harness types with a real keyboard map; if a browser mishandles a key (e.g. a doubled space), that is part of what is measured, not corrected.

## What Sweef cannot do that Chromium does

Sweef is a lightweight browser with its own engine (Go, QuickJS), not a Blink/V8 browser. Honest list of what the comparison above does **not** price in:

- **No JIT.** JavaScript runs in an interpreter (QuickJS). Heavy JS (large SPAs, games, in-browser editors, WebAssembly-heavy sites) is much slower than V8 with TurboFan/Sparkplug; the "heavy" and "SPA" fixtures only exercise a light amount of script and favour Sweef compared with real sites.
- **Page compatibility.** A far smaller share of the web platform than Chromium: layout edge cases, newer CSS and DOM APIs, and (observed while building this harness) detached ` + "`new Image().src = ...`" + ` tracking pixels are not fetched. Sites that need a modern browser may render partially or not at all.
- **No DRM / EME** (Netflix, Spotify web, etc.), **no extensions** (Chrome Web Store), **no WebRTC** (video calls), no WebGL/WebGPU acceleration comparable to Chromium's, limited media codec coverage, no Service Workers-based offline apps, no Chrome sync/profile ecosystem, no PDF viewer or devtools equivalent of Chromium's.
- **No multi-process site isolation.** One process means a crash or a hostile page takes the whole browser down; Chromium's memory cost buys sandboxing and per-tab fault isolation, which this benchmark does not value.
- **Accessibility, IME, printing, HiDPI polish, GPU rasterization, hardware video decode** are mature in Chromium.

Where Chromium wins a row above, it is stated in the verdict column; Sweef's advantage on a row is its footprint (one process, one binary), not capability.
`)
}
