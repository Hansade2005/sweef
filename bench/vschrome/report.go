// report.go: results JSON -> docs/vs-chrome.md. Every number in the document comes from the JSON; the only
// hand-written parts are the method and caveat texts below and the optional <label>.notes.md next to the JSON.
// Rule: no "faster / lighter / better" wording unless the run is complete (all iterations, both browsers, nothing
// missing) and the browsers' per-run ranges do not overlap.

type rep struct {
	r     *Results
	b     *strings.Builder
	names []string
}

func cmdReport(args []string) {
	fl := flag.NewFlagSet("report", flag.ExitOnError)
	in := fl.String("in", "", "results JSON")
	out := fl.String("out", "docs/vs-chrome.md", "markdown output")
	_ = fl.Parse(args)
	if *in == "" {
		fatalf("report: -in is required")
	}
	raw, err := os.ReadFile(*in)
	if err != nil {
		fatalf("%v", err)
	}
	var res Results
	if err := json.Unmarshal(raw, &res); err != nil {
		fatalf("%v", err)
	}
	notes, _ := os.ReadFile(strings.TrimSuffix(*in, ".json") + ".notes.md")
	md := render(&res, filepath.Base(*in), string(notes))
	if err := os.WriteFile(*out, []byte(md), 0o644); err != nil {
		fatalf("%v", err)
	}
	fmt.Println("wrote", *out)
}

func (p *rep) f(format string, a ...any) { fmt.Fprintf(p.b, format, a...) }

func (p *rep) iters(name string) []*Iter {
	if b := p.r.Browsers[name]; b != nil {
		return b.Iters
	}
	return nil
}

// collect gathers one value per iteration.
func (p *rep) collect(name string, f func(*Iter) (float64, bool)) []float64 {
	var out []float64
	for _, it := range p.iters(name) {
		if v, ok := f(it); ok {
			out = append(out, v)
		}
	}
	return out
}

// pooled gathers every sample of a latency series over all iterations, plus the per-iteration medians.
func (p *rep) pooled(name, key string) (all, perRun []float64, missed int) {
	for _, it := range p.iters(name) {
		all = append(all, it.Lat[key]...)
		if len(it.Lat[key]) > 0 {
			perRun = append(perRun, median(it.Lat[key]))
		}
		missed += it.LatFail[key]
	}
	return
}

func fms(v float64) string {
	switch {
	case math.IsNaN(v):
		return "n/a"
	case v >= 100:
		return fmt.Sprintf("%.0f", v)
	case v >= 10:
		return fmt.Sprintf("%.1f", v)
	}
	return fmt.Sprintf("%.2f", v)
}

func rng3(v []float64) string {
	if len(v) == 0 {
		return "n/a"
	}
	return fmt.Sprintf("%s (%s–%s)", fms(median(v)), fms(minOf(v)), fms(maxOf(v)))
}

func mib(kib float64) float64 { return kib / 1024 }

func humanB(n int64) string {
	switch {
	case n >= 1<<30:
		return fmt.Sprintf("%.2f GiB", float64(n)/(1<<30))
	case n >= 1<<20:
		return fmt.Sprintf("%.1f MiB", float64(n)/(1<<20))
	case n >= 1<<10:
		return fmt.Sprintf("%.1f KiB", float64(n)/(1<<10))
	}
	return fmt.Sprintf("%d B", n)
}

// verdict compares two series of per-run values where lower is better.
func (p *rep) verdict(sw, ch []float64) string {
	if !p.r.Complete {
		return "n/a (incomplete run)"
	}
	if len(sw) == 0 || len(ch) == 0 {
		return "n/a"
	}
	ms, mc := median(sw), median(ch)
	ratio := ms / mc
	switch {
	case overlap(sw, ch) || (ratio > 0.9 && ratio < 1.1):
		return fmt.Sprintf("no clear difference (ranges overlap), ratio %.2f", ratio)
	case ratio < 1:
		return fmt.Sprintf("**Sweef lower** (%.2fx of Chromium)", ratio)
	}
	return fmt.Sprintf("**Chromium lower** (Sweef %.2fx Chromium)", ratio)
}

func render(res *Results, srcName, notes string) string {
	p := &rep{r: res, b: &strings.Builder{}, names: []string{"sweef", "chromium"}}
	m := res.Meta
	dirty := ""
	if m.Dirty {
		dirty = " (working tree had uncommitted changes)"
	}
	p.f("# Sweef desktop GUI vs Chromium (with its browser UI)\n\n")
	p.f("_Generated by `bench/vschrome` from `bench/vschrome/results/%s`. Do not edit by hand: re-run `scripts/bench/vschrome.sh`._\n\n", srcName)
	p.f("**Run `%s`** — Sweef commit `%s`%s (source: %s) — %s — N = %d per browser.\n\n", m.Label, m.Commit, dirty, m.SrcMode, m.Date, m.Runs)
	if res.Complete {
		p.f("**Status: COMPLETE.** Every planned run finished for both browsers; the comparison columns below are allowed to say which side is lower.\n\n")
	} else {
		p.f("**Status: INCOMPLETE — no headline.** At least one planned run did not finish for one of the browsers (or this is a smoke run), so this document deliberately contains no \"faster\" / \"lighter\" verdicts; the tables are the raw medians of what did run.\n\n")
		for _, pr := range res.Problems {
			p.f("- %s\n", pr)
		}
		p.f("\n")
	}
	p.f("This is a **relative** comparison measured on Xvfb (software presentation, no GPU). Absolute numbers on a GPU desktop with a compositor will differ; both browsers pay the same X-server cost, so the comparison between them is what is meaningful. See [Method](#method) and [Weaknesses of the method](#weaknesses-of-the-method) before quoting anything.\n\n")

	p.f("**What \"Chromium\" is here.** `%s` — Playwright's Chromium build, not branded Google Chrome: no Google services, no sync, no Google API keys, no proprietary codecs/DRM, a sandbox-policy-managed profile. Same Blink, V8, Skia and browser-UI code as Chrome, run headed with the full browser UI (tab strip, toolbar, omnibox, dropdown). It is **not** `--headless`.\n\n", res.Meta.Browsers["chromium"].Version)

	p.environment()
	if res.Complete {
		p.headline()
	}
	p.startup()
	p.memory()
	p.disk()
	p.latency()
	p.loads()
	p.idle()
	p.calibration()
	p.runQuality()
	if strings.TrimSpace(notes) != "" {
		p.f("\n## Notes on this run\n\n%s\n", strings.TrimSpace(notes))
	}
	p.method()
	p.caveats()
	return p.b.String()
}

func (p *rep) environment() {
	m := p.r.Meta
	p.f("## Environment\n\n| | |\n|---|---|\n")
	p.f("| date | %s |\n| CPU | %s, %d logical cores |\n| RAM | %d MiB |\n| kernel | %s |\n| X server | Xvfb %s: `%s` |\n| window | %s in both browsers (no window manager: Chromium at 0,0 as requested; Sweef centres its own window; all coordinates are taken relative to the window origin read from the server) |\n| load average at start | `%s` (the harness waits up to 2 min for < 0.2 foreign cores before every iteration; it runs at nice -10 so that neighbours disturb it less) |\n| Go | %s |\n",
		m.Date, m.CPU, m.Cores, m.MemMiB, m.Kernel, m.Xvfb, m.XvfbArgs, m.Window, m.Load, m.Go)
	for _, n := range []string{"sweef", "chromium"} {
		b := m.Browsers[n]
		p.f("| %s | %s — `%s`; %s |\n", n, b.Name, b.Version, b.Note)
	}
	p.f("\nLaunch arguments: Sweef `%s`; Chromium `%s`.\n\n", strings.Join(m.Browsers["sweef"].Args, " "), strings.Join(m.Browsers["chromium"].Args, " "))
}

type row struct {
	name   string
	sw, ch []float64
	unit   string
}

func (p *rep) headline() {
	var rows []row
	add := func(name, unit string, f func(*Iter) (float64, bool)) {
		rows = append(rows, row{name, p.collect("sweef", f), p.collect("chromium", f), unit})
	}
	for _, sc := range []struct{ k, n string }{{"cold_fresh_profile", "cold cache"}, {"warm_fresh_profile", "warm cache"}} {
		k := sc.k
		add("start to first frame with browser UI, "+sc.n, "ms", func(it *Iter) (float64, bool) { return it.Startup[k].FirstUIMs, it.Startup[k].OK })
	}
	add("start to new-tab page ready, warm cache", "ms", func(it *Iter) (float64, bool) { s := it.Startup["warm_fresh_profile"]; return s.NTPMs, s.OK })
	add("memory, whole process tree, 1 tab (PSS)", "MiB", func(it *Iter) (float64, bool) {
		if it.Mem1 == nil {
			return 0, false
		}
		return mib(float64(it.Mem1.PSSKiB)), true
	})
	add("memory, whole process tree, 10 tabs (PSS)", "MiB", func(it *Iter) (float64, bool) {
		if it.Mem10 == nil {
			return 0, false
		}
		return mib(float64(it.Mem10.PSSKiB)), true
	})
	add("idle CPU, 30 s, static page (browser tree, % of one core)", "%", func(it *Iter) (float64, bool) {
		if it.Idle == nil {
			return 0, false
		}
		return it.Idle.TreeCPUs / it.Idle.Seconds * 100, true
	})
	for _, k := range []struct{ key, name string }{
		{"key_dropdown_open", "keystroke, dropdown open"}, {"key_dropdown_closed", "keystroke, dropdown closed (opens)"},
		{"tab_switch", "tab switch (Ctrl+Tab), first visible change"}, {"new_tab", "new tab (Ctrl+T), first visible change"}} {
		_, swr, _ := p.pooled("sweef", k.key)
		_, chr, _ := p.pooled("chromium", k.key)
		rows = append(rows, row{k.name + ", p50 (per-run medians)", swr, chr, "ms"})
	}
	for _, pg := range []string{"article", "heavy", "spa"} {
		pg := pg
		add("load "+pg+" page, to first content frame", "ms", func(it *Iter) (float64, bool) { l, ok := it.Loads[pg]; return l.FirstMs, ok && l.OK })
		add("load "+pg+" page, to load event", "ms", func(it *Iter) (float64, bool) { l, ok := it.Loads[pg]; return l.LoadMs, ok && l.OK })
	}
	p.f("## Summary (lower is better in every row)\n\n| metric | Sweef median (min–max) | Chromium median (min–max) | verdict |\n|---|---|---|---|\n")
	for _, r := range rows {
		p.f("| %s | %s %s | %s %s | %s |\n", r.name, rng3(r.sw), r.unit, rng3(r.ch), r.unit, p.verdict(r.sw, r.ch))
	}
	var d1, d2 Disk
	d1, d2 = p.r.Meta.Disk["sweef"], p.r.Meta.Disk["chromium"]
	if d1.ApparentB > 0 && d2.ApparentB > 0 {
		p.f("| installed size (apparent) | %s | %s | %s |\n", humanB(d1.ApparentB), humanB(d2.ApparentB), diskVerdict(d1.ApparentB, d2.ApparentB))
		p.f("| compressed (gzip -6) | %s | %s | %s |\n", humanB(d1.GzipB), humanB(d2.GzipB), diskVerdict(d1.GzipB, d2.GzipB))
	}
	p.f("\n\"No clear difference\" means the per-run ranges overlap or the ratio is within 10%%. Rows where Chromium is lower are Chromium's wins and are not hidden: see the detailed tables. Everything in this table is measured on Xvfb; what it does not measure is listed under [Weaknesses of the method](#weaknesses-of-the-method) and [What Sweef cannot do](#what-sweef-cannot-do-that-chromium-does).\n\n")
}

func diskVerdict(sw, ch int64) string {
	r := float64(sw) / float64(ch)
	if r < 1 {
		return fmt.Sprintf("**Sweef smaller** (%.2fx of Chromium)", r)
	}
	return fmt.Sprintf("**Chromium smaller** (Sweef %.2fx)", r)
}

func (p *rep) startup() {
	p.f("## 1. Cold start\n\nTime from `exec` of the browser to (a) the first frame in which the browser's own UI is painted (top 88 px of the window: at least 60%% light pixels and at least 150 dark text/icon pixels, found by reading the framebuffer when the X server reports damage), (b) the new-tab page being ready (the page area has non-blank content and has not changed for 700 ms), and (c) the window being mapped. Median (min–max) over %d runs; the new Xvfb is started before the timer.\n\n", p.r.Meta.Runs)
	p.f("| scenario | browser | window mapped (ms) | first UI frame (ms) | new-tab page ready (ms) |\n|---|---|---|---|---|\n")
	for _, sc := range []struct{ k, n string }{
		{"cold_fresh_profile", "**cold** file cache (`drop_caches` before launch), fresh profile"},
		{"warm_fresh_profile", "warm file cache, fresh profile"},
		{"warm_used_profile", "warm file cache, profile used before (second launch)"}} {
		for _, n := range p.names {
			k := sc.k
			w := p.collect(n, func(it *Iter) (float64, bool) { return it.Startup[k].WindowMs, it.Startup[k].OK })
			u := p.collect(n, func(it *Iter) (float64, bool) { return it.Startup[k].FirstUIMs, it.Startup[k].OK })
			t := p.collect(n, func(it *Iter) (float64, bool) { return it.Startup[k].NTPMs, it.Startup[k].OK })
			p.f("| %s | %s | %s | %s | %s |\n", sc.n, n, rng3(w), rng3(u), rng3(t))
		}
	}
	p.f("\n")
}

func (p *rep) memory() {
	p.f("## 2. Memory with UI\n\nSum of `Pss` from `/proc/PID/smaps_rollup` over every process of the browser (all processes whose environment carries the run's tag: main, zygote, GPU, renderers, utility, crashpad for Chromium; the single process for Sweef), read after a %d s settle. RSS sum is given for reference only (it double-counts shared pages). Median (min–max) over runs. 10 tabs = the same three fixture pages cycled (article, heavy, SPA).\n\n", p.r.Meta.SettleSecs)
	p.f("| tabs | browser | PSS (MiB) | RSS sum (MiB) | processes |\n|---|---|---|---|---|\n")
	for _, tabs := range []int{1, 10} {
		for _, n := range p.names {
			get := func(f func(*MemSnap) float64) []float64 {
				return p.collect(n, func(it *Iter) (float64, bool) {
					m := it.Mem1
					if tabs == 10 {
						m = it.Mem10
					}
					if m == nil {
						return 0, false
					}
					return f(m), true
				})
			}
			pss := get(func(m *MemSnap) float64 { return mib(float64(m.PSSKiB)) })
			rss := get(func(m *MemSnap) float64 { return mib(float64(m.RSSKiB)) })
			pr := get(func(m *MemSnap) float64 { return float64(m.Procs) })
			p.f("| %d | %s | %s | %s | %s |\n", tabs, n, rng3(pss), rng3(rss), rng3(pr))
		}
	}
	// breakdown by process name
	p.f("\nWhere the PSS goes (median over runs of the per-process-name PSS sum, MiB):\n\n| tabs | browser | breakdown |\n|---|---|---|\n")
	for _, tabs := range []int{1, 10} {
		for _, n := range p.names {
			by := map[string][]float64{}
			for _, it := range p.iters(n) {
				m := it.Mem1
				if tabs == 10 {
					m = it.Mem10
				}
				if m == nil {
					continue
				}
				for k, v := range m.ByComm {
					by[k] = append(by[k], mib(float64(v)))
				}
			}
			type kv struct {
				k string
				v float64
			}
			var l []kv
			for k, v := range by {
				l = append(l, kv{k, median(v)})
			}
			sort.Slice(l, func(i, j int) bool { return l[i].v > l[j].v })
			var parts []string
			for _, e := range l {
				if e.v >= 0.5 {
					parts = append(parts, fmt.Sprintf("%s %.0f", e.k, e.v))
				}
			}
			p.f("| %d | %s | %s |\n", tabs, n, strings.Join(parts, ", "))
		}
	}
	p.f("\n")
}

func (p *rep) disk() {
	p.f("## 3. Disk footprint\n\n| browser | what | files | apparent size | on disk (blocks) | gzip -6 | xz -6 |\n|---|---|---|---|---|---|---|\n")
	for _, n := range p.names {
		d, ok := p.r.Meta.Disk[n]
		if !ok {
			continue
		}
		xz := "—"
		if d.XzB > 0 {
			xz = humanB(d.XzB)
		}
		p.f("| %s | %s | %d | %s | %s | %s | %s |\n", n, d.Note, d.Files, humanB(d.ApparentB), humanB(d.OnDiskB), humanB(d.GzipB), xz)
	}
	p.f("\nSweef is one statically linked Go binary (stripped, `-trimpath`); Chromium is a directory tree. Neither count includes shared system libraries or fonts. The Chromium directory is a Playwright download and includes debugging-friendly extras that a branded Chrome package may or may not carry; treat the ratio as indicative.\n\n")
}

func (p *rep) latency() {
	p.f("## 4. Input latency (the headline)\n\nFrom the instant the `XTEST` key-down request is written by the harness (timestamp taken immediately before the write) to the first frame in which the pixels of the region differ from a baseline read just before the key. The region is read from the **root window**, so Chromium's dropdown popup window is included. Detection is event driven (X DAMAGE says a rectangle of the screen was drawn, then the pixels are read back and compared; damage that leaves the pixels identical is ignored), so the harness puts no polling load on the X server. Percentiles are over **all** samples of all runs (nearest rank); the last column is the min–max of the per-run medians.\n\n")
	p.f("| action | browser | n | p50 (ms) | p90 | p99 | max | per-run median range | missed |\n|---|---|---|---|---|---|---|---|---|\n")
	series := []struct{ key, name string }{
		{"key_dropdown_open", "keystroke in omnibox, dropdown **open** (30 letters, `thequickbrownfoxjumpsoverlazyd`, 80–230 ms apart)"},
		{"key_dropdown_closed", "first keystroke in omnibox, dropdown **closed** (it opens on this key)"},
		{"tab_switch", "tab switch, Ctrl+Tab: first changed pixel anywhere in the window"},
		{"tab_switch_content", "tab switch, Ctrl+Tab: first changed pixel in the page area"},
		{"new_tab", "new tab, Ctrl+T: first changed pixel anywhere in the window"},
		{"new_tab_content", "new tab, Ctrl+T: first changed pixel in the page area"}}
	for _, s := range series {
		for _, n := range p.names {
			all, per, miss := p.pooled(n, s.key)
			if len(all) == 0 {
				p.f("| %s | %s | 0 | n/a | | | | | %d |\n", s.name, n, miss)
				continue
			}
			p.f("| %s | %s | %d | %s | %s | %s | %s | %s–%s | %d |\n", s.name, n, len(all), fms(pct(all, 50)), fms(pct(all, 90)), fms(pct(all, 99)), fms(maxOf(all)), fms(minOf(per)), fms(maxOf(per)), miss)
		}
	}
	p.f("\n")
	if p.r.Complete {
		for _, k := range []string{"key_dropdown_open", "key_dropdown_closed"} {
			a, _, _ := p.pooled("sweef", k)
			b, _, _ := p.pooled("chromium", k)
			if len(a) > 0 && len(b) > 0 {
				p.f("- `%s`: p50 Sweef %s ms vs Chromium %s ms; p99 Sweef %s ms vs Chromium %s ms.\n", k, fms(pct(a, 50)), fms(pct(b, 50)), fms(pct(a, 99)), fms(pct(b, 99)))
			}
		}
		p.f("\n")
	}
}

func (p *rep) loads() {
	p.f("## 5. Page load\n\nFrom the Enter key-down (typed URL, from `about:blank`, fresh profile and cache for every run) to: **first content frame** (the first frame in which the page area below y = 340 px (below anything the omnibox dropdown can cover) contains at least 600 non-background pixels), **load event** (local pages only: the page's `load` handler reports to the fixture server, which timestamps it; includes JS and image loading, and one request of beacon latency), **visually settled** (last pixel change in that region (same area) before a 1 s quiet period; capped at 40 s). Wire bytes: local pages by a byte counter around the fixture server's sockets (HTTP headers included, no compression offered by the server for either browser); real pages by the recording CONNECT proxy (TLS bytes as sent, from `bench/datasaver`'s recorder). Median (min–max).\n\n")
	p.f("| page | browser | first content (ms) | load event (ms) | visually settled (ms) | bytes in | bytes out | HTTP requests |\n|---|---|---|---|---|---|---|---|\n")
	pages := []struct{ k, n string }{{"article", "local: text article (~100 KB HTML)"}, {"heavy", "local: heavy (12 images, 3 scripts, CSS)"}, {"spa", "local: SPA-like (JS renders 240 items from JSON)"}}
	for _, pg := range pages {
		p.loadRows(pg.k, pg.n, true)
	}
	if len(p.r.Meta.Sites) > 0 {
		p.f("\n### Real public pages (through the sandbox proxy)\n\nThe first %d pages of `bench/datasaver/sites.txt`, in file order, that load in **both** browsers (one probe load each, same method; the rule is fixed and nothing is chosen by timing). The network and the sites are outside our control: these runs are noisier than the local ones. No `load` event column: a third-party page cannot report it.\n\n", len(p.r.Meta.Sites))
		p.f("| page | browser | first content (ms) | visually settled (ms) | bytes in | bytes out | connections |\n|---|---|---|---|---|---|---|\n")
		for i, s := range p.r.Meta.Sites {
			p.loadRows(fmt.Sprintf("real%d", i+1), s, false)
		}
		if len(p.r.Meta.Sites) < 5 {
			p.f("\nOnly %d real sites loaded in both browsers.\n", len(p.r.Meta.Sites))
		}
		for _, nt := range p.r.Meta.SitesNote {
			p.f("\n- %s", nt)
		}
	}
	p.f("\n\n")
}

func (p *rep) loadRows(key, name string, local bool) {
	for _, n := range p.names {
		get := func(f func(LoadSample) float64) []float64 {
			return p.collect(n, func(it *Iter) (float64, bool) {
				l, ok := it.Loads[key]
				if !ok || !l.OK {
					return 0, false
				}
				return f(l), true
			})
		}
		first := get(func(l LoadSample) float64 { return l.FirstMs })
		load := get(func(l LoadSample) float64 { return l.LoadMs })
		settle := get(func(l LoadSample) float64 { return l.SettleMs })
		in := get(func(l LoadSample) float64 { return float64(l.WireIn) / 1024 })
		out := get(func(l LoadSample) float64 { return float64(l.WireOut) / 1024 })
		cn := get(func(l LoadSample) float64 {
			if local {
				return float64(l.Reqs)
			}
			return float64(l.Conns)
		})
		if local {
			p.f("| %s | %s | %s | %s | %s | %s KiB | %s KiB | %s |\n", name, n, rng3(first), rng3(load), rng3(settle), rng3(in), rng3(out), rng3(cn))
		} else {
			p.f("| %s | %s | %s | %s | %s KiB | %s KiB | %s |\n", name, n, rng3(first), rng3(settle), rng3(in), rng3(out), rng3(cn))
		}
	}
}

func (p *rep) idle() {
	p.f("## 6. Idle CPU\n\n%d s with the browser open on the static article page and nothing touching it: user+system jiffies of every process of the browser tree, sampled once a second (per-process deltas, so processes that start or exit are included). \"Xvfb\" is the X server's own CPU in the same window; \"other\" is whatever else the machine was doing (it should be close to zero; large values mark a disturbed run).\n\n", p.r.Meta.IdleSecs)
	p.f("| browser | browser tree CPU (s) | = %% of one core | Xvfb CPU (s) | other on machine (s) | max processes |\n|---|---|---|---|---|---|\n")
	for _, n := range p.names {
		get := func(f func(*IdleCPU) float64) []float64 {
			return p.collect(n, func(it *Iter) (float64, bool) {
				if it.Idle == nil || !it.Idle.OK {
					return 0, false
				}
				return f(it.Idle), true
			})
		}
		p.f("| %s | %s | %s | %s | %s | %s |\n", n, rng3(get(func(i *IdleCPU) float64 { return i.TreeCPUs })),
			rng3(get(func(i *IdleCPU) float64 { return i.TreeCPUs / i.Seconds * 100 })),
			rng3(get(func(i *IdleCPU) float64 { return i.XvfbCPUs })), rng3(get(func(i *IdleCPU) float64 { return i.OtherCPUs })),
			rng3(get(func(i *IdleCPU) float64 { return float64(i.MaxProcs) })))
	}
	p.f("\n")
}

