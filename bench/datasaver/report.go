func reportMain(args []string) {
	fs := flag.NewFlagSet("report", flag.ExitOnError)
	in := fs.String("in", "", "results json")
	md := fs.String("md", "docs/data-saver-bench.md", "markdown output")
	fs.Parse(args)
	b, err := os.ReadFile(*in)
	if err != nil {
		fatalf("%v", err)
	}
	var res Results
	if err := json.Unmarshal(b, &res); err != nil {
		fatalf("%v", err)
	}
	if err := writeReport(&res, *md, *in); err != nil {
		fatalf("%v", err)
	}
	fmt.Fprintf(os.Stderr, "wrote %s\n", *md)
}

func modeTitle(m string) string {
	switch m {
	case ModeSweefOff:
		return "Sweef off"
	case ModeSweefStandard:
		return "Sweef standard"
	case ModeSweefStrict:
		return "Sweef strict"
	case ModeChromium:
		return "Chromium"
	case ModeChromiumSD:
		return "Chromium + Save-Data"
	case ModeChromiumNoImg:
		return "Chromium, images off"
	}
	return m
}

func cellStr(a Agg, f func(float64) string) string {
	if a.N == 0 {
		return "n/a"
	}
	return fmt.Sprintf("%s (%s to %s)", f(a.Median), f(a.Min), f(a.Max))
}

func fmtKB(b float64) string  { return fmt.Sprintf("%.0f", b/1e3) }
func fmtInt(b float64) string { return fmt.Sprintf("%.0f", b) }
func fmtMs(b float64) string  { return fmt.Sprintf("%.0f", b) }
func fmt1(b float64) string   { return fmt.Sprintf("%.1f", b) }

type mdw struct{ sb strings.Builder }

func (w *mdw) f(format string, a ...any) { fmt.Fprintf(&w.sb, format, a...) }
func (w *mdw) p(s string)                { w.sb.WriteString(s); w.sb.WriteString("\n") }

func (w *mdw) table(head []string, rows [][]string) {
	w.p("| " + strings.Join(head, " | ") + " |")
	seps := make([]string, len(head))
	for i := range seps {
		seps[i] = "---"
		if i > 0 {
			seps[i] = "---:"
		}
	}
	w.p("|" + strings.Join(seps, "|") + "|")
	for _, r := range rows {
		w.p("| " + strings.Join(r, " | ") + " |")
	}
	w.p("")
}

func writeReport(res *Results, mdPath, resultsPath string) error {
	ix := newIndex(res)
	inc, exc := ix.Included()
	hl := ix.headline()
	w := &mdw{}
	rel := resultsPath
	if wd, err := os.Getwd(); err == nil {
		if r, err := filepath.Rel(wd, resultsPath); err == nil {
			rel = r
		}
	}

	w.p("# Data Saver benchmark")
	w.p("")
	w.f("Generated by `go run ./bench/datasaver` from `%s` (run started %s, finished %s). Do not edit by hand: rerun the tool or `go run ./bench/datasaver report`.\n\n", rel, res.Started, res.Finished)
	w.p("Contract: docs/data-saver.md, section Benchmark. Everything below is measured the same way for every browser, by a recording proxy that neither browser controls (see Method). Numbers are bytes on the wire, cold cache unless a table says warm.")
	w.p("")

	// ---- headline
	w.p("## Headline")
	w.p("")
	if hl.Allowed {
		w.f("Every mode completed the same %d sites with all %d runs, so percentages are allowed. Wire bytes (in + out), cold cache, summed over the included sites, median of per-run totals with min and max over the %d runs. Positive means fewer bytes than the base.\n\n", len(inc), res.Runs, res.Runs)
		var rows [][]string
		for _, r := range hl.Rows {
			rows = append(rows, []string{r.Label, kb(r.BaseSum), kb(r.Sum), fmt.Sprintf("%.1f%% (%.1f%% to %.1f%%)", r.SavedPct.Median, r.SavedPct.Min, r.SavedPct.Max)})
		}
		w.table([]string{"Comparison", "Base (sum of site medians)", "Mode (sum of site medians)", "Saved, median (min to max over runs)"}, rows)
		w.p("A saving against Chromium is not a claim that Sweef shows the same page: see the caveat on what each engine fetches.")
	} else {
		w.p("**No \"% saved\" figure is printed for this run.** The tool only prints one when every mode completed the same sites, and this run does not meet that bar.")
		w.p("")
		w.f("Reason: %s.\n", hl.Reason)
	}
	w.p("")

	// ---- summary per mode
	w.p("## Summary per mode (cold, included sites only)")
	w.p("")
	w.f("%d of %d listed sites are included (see Excluded sites). \"Pages per 100 MB\" is 100,000,000 bytes divided by the mean wire bytes (in + out) per page; one value per run index, shown as median with min to max over the %d runs. Requests are what the browser itself counted (CDP `requestWillBeSent` for Chromium, the engine's network log for Sweef); connections are counted by the proxy.\n\n", len(inc), len(res.Sites), res.Runs)
	var rows [][]string
	sums := map[string]ModeSummary{}
	for _, m := range res.Modes {
		s := ix.summarize(m, inc)
		sums[m] = s
		var conns []float64
		for _, st := range inc {
			conns = append(conns, aggOf(ix.series(st.URL, m, false, func(v Visit) float64 { return float64(v.Conns) })).Median)
		}
		rows = append(rows, []string{modeTitle(m), cellStr(s.MeanBytes, kb2), cellStr(s.Pages100MB, fmt1), cellStr(s.Requests, fmt1), fmt1(mean(conns)), cellStr(s.ReadyMs, fmtMs)})
	}
	w.table([]string{"Mode", "Mean wire bytes per page", "Pages per 100 MB", "Requests per page", "Connections per page", "Time to ready, ms (median over sites)"}, rows)
	for m, why := range res.Skipped {
		if strings.HasPrefix(m, "sweef-") || strings.HasPrefix(m, "chromium") {
			w.f("* `%s` was **not run**: %s.\n", m, why)
		}
	}
	w.p("")
	w.p("Time to ready is the browser's own definition: Chromium = `Page.navigate` until the `load` event; Sweef = `NewTab(url)` returns, which includes the engine's script execution and its event-loop settle budget (default 1500 ms when the page has script). The two are not the same event, so compare times between Sweef modes and between Chromium modes, not across.")
	w.p("")

	// ---- per site cold
	siteTable := func(title, note string, warm bool, f func(Visit) float64, ff func(float64) string) {
		w.p("## " + title)
		w.p("")
		if note != "" {
			w.p(note)
			w.p("")
		}
		head := []string{"Site"}
		for _, m := range res.Modes {
			head = append(head, modeTitle(m))
		}
		var rows [][]string
		for _, s := range inc {
			row := []string{s.ShortName()}
			for _, m := range res.Modes {
				row = append(row, cellStr(aggOf(ix.series(s.URL, m, warm, f)), ff))
			}
			rows = append(rows, row)
		}
		w.table(head, rows)
	}
	total := func(v Visit) float64 { return float64(v.Total()) }
	siteTable("Wire bytes per site, cold (KB, median and min to max of runs)", "In plus out, from the recording proxy. 1 KB = 1000 bytes.", false, total, fmtKB)
	siteTable("Wire bytes per site, warm second visit (KB)", "Chromium: a new browser process on the same profile directory (disk cache, cookies and storage kept). Sweef: the same engine and context, idle connections closed (the engine's in-memory resource cache is kept).", true, total, fmtKB)
	siteTable("Requests per site, cold", "", false, func(v Visit) float64 { return float64(v.Requests) }, fmtInt)
	siteTable("Connections per site, cold (counted by the proxy)", "", false, func(v Visit) float64 { return float64(v.Conns) }, fmtInt)
	siteTable("Time to ready per site, cold (ms)", "See the note under the summary table: the two engines define ready differently.", false, func(v Visit) float64 { return v.ReadyMs }, fmtMs)
	siteTable("Pages per 100 MB per site, cold", "100,000,000 bytes divided by the wire bytes of one visit of that page.", false, func(v Visit) float64 { return pagesPer100MB(float64(v.Total())) }, fmt1)

	// ---- warm summary
	w.p("## Cache effect (warm second visit vs cold, same sites)")
	w.p("")
	rows = nil
	for _, m := range res.Modes {
		s := sums[m]
		rows = append(rows, []string{modeTitle(m), cellStr(s.MeanBytes, kb2), cellStr(s.WarmMeanBytes, kb2), cellStr(s.WarmPages100, fmt1), fmt.Sprintf("%.0f%%", 100*s.WarmVsCold)})
	}
	w.table([]string{"Mode", "Cold mean bytes per page", "Warm mean bytes per page", "Warm pages per 100 MB", "Warm as share of cold (sum of site medians)"}, rows)

	// ---- cross-check
	w.p("## Cross-check: proxy bytes vs the browsers' own counters")
	w.p("")
	w.p("The proxy sees encrypted bytes on the socket, which includes TLS handshakes, TLS record framing, HTTP/2 framing, request headers and anything the page requested that the browser does not itemise. Chromium's CDP `encodedDataLength` is the response transfer size (headers and body as received, before TLS record overhead). CDP has no request-size counter, so \"CDP out\" is an estimate: request line plus the header lines CDP reports for each request, uncompressed (HTTP/2 compresses headers, so this over-states), plus POST bodies. Sweef's own counters (`DataStats.WireIn/WireOut`, exact socket totals of the context) are shown when the engine API exists; the engine counts at its dialer, which also sees the CONNECT exchange with the recorder (about 40 bytes in and 90 out per connection), so that exchange is added to the proxy figure for this comparison only.")
	w.p("")
	rows = nil
	var worst []string
	for _, m := range res.Modes {
		var pin, bin, pout, bout, conns, n float64
		var eIn, eOut, pInE, pOutE float64
		eN := 0
		for _, s := range inc {
			for _, c := range ix.get(s.URL, m) {
				v := c.Cold
				pin += float64(v.WireIn)
				pout += float64(v.WireOut)
				conns += float64(v.Conns)
				n++
				if v.BrowserIn >= 0 {
					bin += float64(v.BrowserIn)
					bout += float64(v.BrowserOut)
				}
				if v.Engine != nil {
					eIn += float64(v.Engine.WireIn)
					eOut += float64(v.Engine.WireOut)
					// the engine's socket counter also sees the CONNECT exchange with the recorder; add it back
					pInE += float64(v.WireIn + v.HandshakeIn)
					pOutE += float64(v.WireOut + v.HandshakeOut)
					eN++
				}
			}
		}
		if n == 0 {
			continue
		}
		switch {
		case !isSweef(m):
			ov := (pin - bin) / math.Max(conns, 1)
			rows = append(rows, []string{modeTitle(m), "CDP", kb(pin), kb(bin), pct(pin, bin), kb(pout), kb(bout) + " (estimate)", pct(pout, bout), fmt.Sprintf("%.1f KB", ov/1e3)})
		case eN > 0:
			ov := (pInE - eIn) / math.Max(conns, 1)
			rows = append(rows, []string{modeTitle(m), "engine DataStats", kb(pInE), kb(eIn), pct(pInE, eIn), kb(pOutE), kb(eOut), pct(pOutE, eOut), fmt.Sprintf("%.1f KB", ov/1e3)})
		default:
			rows = append(rows, []string{modeTitle(m), "none yet", kb(pin), "n/a", "n/a", kb(pout), "n/a", "n/a", "n/a"})
		}
		if !isSweef(m) {
			type dd struct {
				site string
				rel  float64
				abs  float64
			}
			var ds []dd
			for _, s := range inc {
				for _, c := range ix.get(s.URL, m) {
					v := c.Cold
					if v.WireIn > 0 && v.BrowserIn >= 0 {
						ds = append(ds, dd{s.ShortName(), float64(v.WireIn-v.BrowserIn) / float64(v.WireIn), float64(v.WireIn - v.BrowserIn)})
					}
				}
			}
			sort.Slice(ds, func(i, j int) bool { return math.Abs(ds[i].rel) > math.Abs(ds[j].rel) })
			for i := 0; i < len(ds) && i < 3; i++ {
				worst = append(worst, fmt.Sprintf("%s: %s, run with proxy %.1f%% above CDP (%s)", modeTitle(m), ds[i].site, 100*ds[i].rel, kb(ds[i].abs)))
			}
		}
	}
	w.table([]string{"Mode", "Own counter", "Proxy in", "Own in", "Proxy vs own, in", "Proxy out", "Own out", "Proxy vs own, out", "In overhead per connection"}, rows)
	if len(worst) > 0 {
		w.p("Largest per-visit gaps (inbound, proxy minus CDP, as a share of the proxy figure):")
		w.p("")
		for _, s := range worst {
			w.p("* " + s)
		}
		w.p("")
	}

	// ---- first/third party
	w.p("## First party vs third party (from the proxy's per-host bytes)")
	w.p("")
	w.p("\"First party\" means the connection's registrable domain equals the page's. Sites that serve their own assets from a different domain (for example a CDN domain owned by the same company) count as third party here, so treat the split as indicative.")
	w.p("")
	rows = nil
	for _, m := range res.Modes {
		var fp, tp, n float64
		for _, s := range inc {
			pd := regDomain(s.Host())
			for _, c := range ix.get(s.URL, m) {
				for _, h := range c.Cold.Hosts {
					if regDomain(h.Host) == pd {
						fp += float64(h.In + h.Out)
					} else {
						tp += float64(h.In + h.Out)
					}
				}
				n++
			}
		}
		if n == 0 {
			continue
		}
		rows = append(rows, []string{modeTitle(m), kb(fp / n), kb(tp / n), fmt.Sprintf("%.0f%%", 100*tp/math.Max(fp+tp, 1))})
	}
	w.table([]string{"Mode", "First-party bytes per page", "Third-party bytes per page", "Third-party share"}, rows)

	// ---- by type for chromium
	hasCDP := false
	for _, m := range res.Modes {
		if !isSweef(m) {
			hasCDP = true
		}
	}
	if hasCDP {
		w.p("## What Chromium fetched (CDP transfer size by resource type, cold, mean per page)")
		w.p("")
		types := []string{"Document", "Stylesheet", "Script", "Image", "Font", "Media", "XHR", "Fetch", "Ping", "Other"}
		head := []string{"Mode"}
		head = append(head, types...)
		rows = nil
		for _, m := range res.Modes {
			if isSweef(m) {
				continue
			}
			row := []string{modeTitle(m)}
			for _, t := range types {
				var sum, n float64
				for _, s := range inc {
					for _, c := range ix.get(s.URL, m) {
						sum += float64(c.Cold.ByType[t])
						n++
					}
				}
				if n == 0 {
					row = append(row, "0")
				} else {
					row = append(row, kb(sum/n))
				}
			}
			rows = append(rows, row)
		}
		w.table(head, rows)
	}
	w.p("## What Sweef requested (engine network log, cold, mean requests per page by guessed type)")
	w.p("")
	w.p("Sweef's engine does not report transfer sizes per request until the DataStats API lands, so only counts are shown. Type is guessed from the response Content-Type.")
	w.p("")
	{
		types := []string{"Document", "Stylesheet", "Script", "Image", "Font", "XHR", "Other"}
		head := append([]string{"Mode"}, types...)
		rows = nil
		for _, m := range res.Modes {
			if !isSweef(m) {
				continue
			}
			row := []string{modeTitle(m)}
			for _, t := range types {
				var sum, n float64
				for _, s := range inc {
					for _, c := range ix.get(s.URL, m) {
						sum += float64(c.Cold.ByTypeCount[t])
						n++
					}
				}
				if n == 0 {
					row = append(row, "0")
				} else {
					row = append(row, fmt1(sum/n))
				}
			}
			rows = append(rows, row)
		}
		if len(rows) > 0 {
			w.table(head, rows)
		}
	}

	// ---- baseline
	if len(res.Baselines) > 0 {
		w.p("## Baseline: about:blank with the same flags and idle window")
		w.p("")
		w.p("What each browser puts on the wire with no page loaded. \"Page\" bytes are what the tables above would count; \"browser-internal\" bytes are connections Chromium opened by itself to its vendor's hosts that the flags do not suppress (see Method). The first must be zero for the measurement to be page-only.")
		w.p("")
		rows = nil
		for _, m := range res.Modes {
			var in, out, cn, iin, iout []float64
			hosts := map[string]bool{}
			for _, b := range res.Baselines {
				if b.Mode == m {
					in = append(in, float64(b.WireIn))
					out = append(out, float64(b.WireOut))
					cn = append(cn, float64(b.Conns))
					iin = append(iin, float64(b.InternalIn))
					iout = append(iout, float64(b.InternalOut))
					for _, h := range b.Hosts {
						hosts[h] = true
					}
				}
			}
			if len(in) == 0 {
				continue
			}
			var hs []string
			for h := range hosts {
				hs = append(hs, h)
			}
			sort.Strings(hs)
			hv := "none"
			if len(hs) > 0 {
				hv = strings.Join(hs, ", ")
			}
			rows = append(rows, []string{modeTitle(m), cellStr(aggOf(in), fmtInt), cellStr(aggOf(out), fmtInt), cellStr(aggOf(cn), fmtInt), cellStr(aggOf(iin), fmtInt), cellStr(aggOf(iout), fmtInt), hv})
		}
		w.table([]string{"Mode", "Page bytes in", "Page bytes out", "Page connections", "Browser-internal bytes in", "Browser-internal bytes out", "Hosts contacted"}, rows)
	}

	// ---- browser internal during visits
	{
		rows = nil
		for _, m := range res.Modes {
			var iin, iout, n float64
			hosts := map[string]bool{}
			for _, s := range inc {
				for _, c := range ix.get(s.URL, m) {
					iin += float64(c.Cold.InternalIn)
					iout += float64(c.Cold.InternalOut)
					n++
					for _, h := range c.Cold.InternalHosts {
						hosts[h] = true
					}
				}
			}
			if n == 0 || len(hosts) == 0 {
				continue
			}
			var hs []string
			for h := range hosts {
				hs = append(hs, h)
			}
			sort.Strings(hs)
			rows = append(rows, []string{modeTitle(m), kb(iin / n), kb(iout / n), strings.Join(hs, ", ")})
		}
		if len(rows) > 0 {
			w.p("## Browser-internal traffic kept out of the page numbers")
			w.p("")
			w.p("Per cold visit, mean. This is real Chromium traffic (it would be billed) but it is not caused by the page, so it is excluded from every table above and shown here instead. Raw per-visit values are in the results JSON (`internal_in`, `internal_out`). A connection is classified as internal only if its host is on a fixed list of vendor hosts AND no request the page made went to that host.")
			w.p("")
			w.table([]string{"Mode", "Internal bytes in", "Internal bytes out", "Hosts"}, rows)
		}
	}

	// ---- save-data
	for _, m := range res.Modes {
		if m != ModeChromiumSD {
			continue
		}
		var sd, tot float64
		for _, s := range inc {
			for _, c := range ix.get(s.URL, m) {
				sd += float64(c.Cold.SaveDataReq)
				tot += float64(c.Cold.Requests)
			}
		}
		w.p("## What the Save-Data header alone does")
		w.p("")
		w.f("The `chromium-savedata` mode only adds `Save-Data: on` to every request through CDP `Network.setExtraHTTPHeaders`; Chromium's own behaviour is unchanged. CDP reported the header on %.0f of %.0f requests (%.0f%%; the rest are requests the header override does not reach, such as cache hits and service-worker traffic). Whatever difference the table shows is what sites chose to do when they saw the header.\n\n", sd, tot, 100*sd/math.Max(tot, 1))
	}

	// ---- excluded
	w.p("## Excluded sites")
	w.p("")
	w.p("Rule, fixed before the run: a site is excluded from every mode if, in any mode and any run, the main document answered HTTP 400 or higher, navigation failed or timed out (one automatic retry for transport errors and timeouts, none for HTTP errors), or a visit did not complete. Nothing is excluded for any other reason, and the frozen list is never edited.")
	w.p("")
	if len(exc) == 0 {
		w.p("None: every listed site completed in every mode.")
	} else {
		for _, e := range exc {
			w.f("* `%s`: %s\n", e.Site, strings.Join(e.Reasons, "; "))
		}
	}
	w.p("")

	// ---- site list
	w.p("## Site list (frozen before the first run)")
	w.p("")
	w.f("`bench/datasaver/sites.txt`, SHA-256 of its entries `%s`. The tool refuses to run if the file no longer matches `sites.txt.sha256`.\n\n", res.SitesHash)
	excl := map[string]bool{}
	for _, e := range exc {
		excl[e.Site] = true
	}
	rows = nil
	for _, s := range res.Sites {
		st := "included"
		if excl[s.URL] {
			st = "excluded"
		}
		rows = append(rows, []string{"`" + s.URL + "`", s.Reason, st})
	}
	w.table([]string{"URL", "Why it is in the list", "Status"}, rows)

	// ---- method
	writeMethod(w, res)

	// ---- env
	writeEnv(w, res)

	w.p("## Caveats")
	w.p("")
	for _, c := range []string{
		"**Single network location, single machine, one day.** All numbers come from one cloud sandbox behind one egress path. Another country, ISP, time of day or CDN edge can change what is served and how it is compressed.",
		"**Pages change daily.** Front pages, ad auctions and A/B tests mean two runs minutes apart differ; that is why every cell has three runs and a min to max range. Treat differences smaller than the range as noise.",
		"**Not the same page.** Sweef's engine and Chromium do not fetch the same set of resources. The tables above show what each actually requested; if one fetches no images or fonts, its byte count is lower for that reason alone and says nothing about a data saver. Only the Sweef off/standard/strict comparison holds the engine constant.",
		"**Headless Chromium without extensions.** No ad blocker, no profile history, no Data Saver of its own. The Chromium user agent has \"Headless\" removed (client hints too) so sites do not serve it a bot page; Sweef sends its default user agent. Sites may treat the two differently, which the exclusion rule only partly catches (a 200 response with a different page is not detected).",
		"**Consent banners and geo variation.** No consent is clicked for any browser. Pages from EU-region edges may show a consent overlay that blocks or defers trackers; this sandbox's region decides which variant is served.",
		"**TLS is re-terminated.** The sandbox's egress gateway terminates TLS with its own certificate chain, so handshake bytes are not exactly what the real site would send. Both browsers see the same chain, so the comparison is fair, but absolute bytes are slightly off from a direct connection. Chromium cannot use QUIC through an HTTP proxy, so it ran HTTP/2 or HTTP/1.1, as did Sweef.",
		"**What is not counted.** TCP/IP headers, DNS lookups (resolved by the upstream proxy), and the CONNECT exchanges between browser, recorder and upstream proxy. TCP/IP headers would add a few percent to every mode alike.",
		"**Plain http:// is not forwarded** by the recorder (the sandbox proxy only tunnels). All listed pages are https; any plain-http sub-resource a page asked for is refused and noted per run, which can make a page slightly smaller than in the wild.",
		"**Sweef proxy routing.** The harness points the engine at its recorder with `Options.ProxyURL`, the same option an application uses (`Options.ProxyURL`); HTTP(S) and WebSocket traffic of the engine both go through it, so both are counted. (Earlier runs of this benchmark reached the transport by reflection and failed any page that opened a WebSocket.)",
		"**Warm-cache definitions differ by necessity.** Chromium's warm visit is a new process on the same profile (disk cache); Sweef's is the same process and context, but the in-memory tier of its HTTP cache is dropped first (`Engine.DropMemoryCache`), so the warm visit is served from the on-disk cache only, as after a restart. Cookies survive in both. Chromium's disk cache is partitioned by site and has its own size limit; Sweef's is one profile-wide directory with a 100 MB cap.",
	} {
		w.p("* " + c)
	}
	w.p("")

	w.p("## Reproduce")
	w.p("")
	w.p("```sh")
	w.p("# from the repository root, with Chromium at /opt/pw-browsers/chromium and HTTPS_PROXY set if egress needs it")
	w.p("scripts/bench/datasaver.sh                 # builds with the engine API when it exists, runs all modes, writes results + this page")
	w.p("# or by hand:")
	w.p("go run ./bench/datasaver -sites bench/datasaver/sites.txt -runs 3")
	w.p("go run -tags datasaver_engine ./bench/datasaver -runs 3   # once engine.DataPolicy exists: adds Sweef standard and strict")
	w.p("go run ./bench/datasaver report -in bench/datasaver/results/<file>.json -md docs/data-saver-bench.md")
	w.p("```")
	w.p("")
	w.p("Results are written to `bench/datasaver/results/YYYY-MM-DD-<label>.json`. The README may quote only the tables in this file.")
	w.p("")

	if err := os.MkdirAll(filepath.Dir(mdPath), 0o755); err != nil {
		return err
	}
	return os.WriteFile(mdPath, []byte(w.sb.String()), 0o644)
}

func kb2(b float64) string { return kb(b) }

func pct(a, b float64) string {
	if b == 0 {
		return "n/a"
	}
	return fmt.Sprintf("%+.1f%%", 100*(a-b)/b)
}

func writeMethod(w *mdw, res *Results) {
	w.p("## Method")
	w.p("")
	w.f("**What is measured.** For every site, mode and run: one cold visit, then one warm visit. Each visit is `load` plus a fixed %.0f s idle window, then the counters are read. The same %.0f s applies to every browser. %d runs per cell; tables show the median with the minimum and maximum. Run order is rotated per run so no mode is always first or last.\n\n", res.IdleSec, res.IdleSec, res.Runs)
	w.p("**The independent counter.** Every browser is pointed at its own tiny recording HTTP CONNECT proxy written for this harness (`bench/datasaver/recproxy.go`), which forwards through the sandbox proxy (`HTTPS_PROXY`) and counts, per connection, the bytes it writes in each direction after the CONNECT handshake. For https it only tunnels, so it sees the encrypted bytes: TLS handshake, TLS records, HTTP/2 or HTTP/1.1 framing. That is what a metered connection bills, minus TCP/IP headers. One recorder is created per browser launch, so runs cannot contaminate each other. The recorder has a test that compares its counts to a byte counter on the far side of a real TLS connection.")
	w.p("")
	w.p("**Cross-check.** The browsers' own counters are collected separately and compared in the cross-check table: Chromium `Network.loadingFinished.encodedDataLength` (plus redirect responses) and request headers from CDP, and Sweef's `DataStats.WireIn/WireOut` once the engine exposes them. The proxy figures are the ones used in every other table; the browser counters are only a check.")
	w.p("")
	w.p("**Chromium.** The binary at `/opt/pw-browsers/chromium`, `--headless=new --no-sandbox`, a fresh `--user-data-dir` for every cold visit and a new process on the same directory for the warm visit. Flags that stop it generating non-page traffic: `--disable-background-networking --disable-sync --disable-component-update --disable-default-apps --disable-domain-reliability --disable-client-side-phishing-detection --safebrowsing-disable-auto-update --disable-breakpad --metrics-recording-only --no-pings` plus feature switches for optimization hints, translate, media router, autofill server and the certificate-transparency updater. The about:blank baseline table shows what remains. CDP is attached with flat sessions and `Target.setAutoAttach` (paused on start) so iframes, workers and service workers are counted too. The `chromium-savedata` mode additionally sets `Save-Data: on` with `Network.setExtraHTTPHeaders`; it does not enable any Chromium data-saving behaviour (the old DataReductionProxy is gone), so it shows what a plain header does. Viewport 1280x720, same as the Sweef engine default.")
	w.p("")
	w.p("**Sweef.** The harness drives the engine in-process (`internal/engine`), one child process per cold visit: fresh engine, fresh cache directory, fresh cookie jar and connection pool, the engine's default context (the one the desktop app browses in, and the only one with the on-disk HTTP cache), default engine options (`DefaultOptions()`, user agent included). `ready` is when `NewTabInContext(url)` returns. The idle window pumps the page's event loop with `Tab.Settle`. Modes `standard` and `strict` apply `engine.PolicyFor(level)` with `SetDataPolicy`; they are only run in a build that has that API (`-tags datasaver_engine`). Sweef `off` today is the engine with nothing blocked, which is what `off` means in the spec.")
	w.p("")
	w.p("**Request counts.** Chromium: CDP `requestWillBeSent` for http(s) URLs, one per redirect hop, cache hits included. Sweef: the engine's own network log (one request event per request, cache hits and 304 revalidations included). Connections are counted by the proxy for both.")
	w.p("")
	w.p("**Pages per 100 MB.** 100,000,000 bytes divided by the mean wire bytes (in plus out) per page over the included sites, computed once per run index and reported as median, min and max over runs. Per-site tables apply the same formula to a single visit.")
	w.p("")
	w.p("**Honesty rules applied.** The tool prints a \"% saved\" figure only if every mode completed the same sites with every run; otherwise the headline section says why it is withheld. Sites are chosen and frozen beforehand and excluded by a fixed mechanical rule. Savings estimates from the engine (`SkippedEstimate`) are never mixed into measured bytes; the benchmark compares only socket bytes.")
	w.p("")
}

