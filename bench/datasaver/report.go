// printConsole prints a short plain-text summary on stdout. It obeys the same headline gate as the report.
func printConsole(res *Results) {
	ix := newIndex(res)
	inc, exc := ix.Included()
	fmt.Printf("\n%d of %d sites included, %d excluded, %d runs\n", len(inc), len(res.Sites), len(exc), res.Runs)
	fmt.Printf("%-22s %14s %18s %10s %12s\n", "mode", "mean KB/page", "pages/100MB", "req/page", "ready ms")
	for _, m := range res.Modes {
		s := ix.summarize(m, inc)
		fmt.Printf("%-22s %14.0f %6.1f (%4.1f-%4.1f) %10.1f %12.0f\n", modeTitle(m), s.MeanBytes.Median/1e3, s.Pages100MB.Median, s.Pages100MB.Min, s.Pages100MB.Max, s.Requests.Median, s.ReadyMs.Median)
	}
	hl := ix.headline()
	if hl.Allowed {
		for _, r := range hl.Rows {
			fmt.Printf("%-48s saved %.1f%% (%.1f to %.1f)\n", r.Label, r.SavedPct.Median, r.SavedPct.Min, r.SavedPct.Max)
		}
	} else {
		fmt.Printf("no %% saved headline: %s\n", hl.Reason)
	}
}
