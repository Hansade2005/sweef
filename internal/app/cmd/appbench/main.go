type report struct {
	sb strings.Builder
}

func (r *report) f(format string, a ...any) { fmt.Fprintf(&r.sb, format, a...) }

func main() {
	out := flag.String("out", "", "report path (default internal/app/BENCH.md in the module)")
	quick := flag.Bool("quick", false, "fewer samples")
	uiDir := flag.String("ui", "", "directory with chrome assets (default: the real UI, ui.FS)")
	placeholder := flag.Bool("placeholder", false, "bench the built-in placeholder chrome instead of ui.FS")
	chromium := flag.String("chromium", "", "chromium binary for the comparison (default: auto-detect under /opt/pw-browsers)")
	noChrome := flag.Bool("skip-chromium", false, "skip the Chromium comparison")
	onlyChrome := flag.Bool("only-chromium", false, "run only the Chromium comparison")
	openProf := flag.String("open-profile", "", "profile only the key that opens the omnibox dropdown; write a CPU profile to this path and exit")
	openScale := flag.Float64("open-scale", 1, "device scale for -open-profile")
	flag.Parse()
	if *openProf != "" {
		openProfile(*openProf, *openScale)
		return
	}
	root := moduleRoot()
	if *out == "" {
		*out = filepath.Join(root, "internal", "app", "BENCH.md")
	}
	runs, samples := 7, 100
	if *quick {
		runs, samples = 3, 30
	}
	var chromeFS fs.FS = ui.FS
	uiName := "real chrome UI (internal/ui, ui.FS)"
	if *placeholder {
		chromeFS = nil
		uiName = "built-in placeholder chrome (internal/app/testdata)"
	}
	if *uiDir != "" {
		chromeFS = os.DirFS(*uiDir)
		uiName = *uiDir
	}

	r := &report{}
	r.f("# GUI benchmarks\n\n")
	r.f("Generated by `go run ./internal/app/cmd/appbench` — do not edit by hand. Every number below was measured by that program on the machine described here; nothing is estimated. Re-run it to reproduce.\n\n")
	r.f("## Environment\n\n")
	r.f("- date: %s\n- commit: %s\n- go: %s %s/%s, GOMAXPROCS=%d\n- cpu: %s\n- chrome UI under test: %s\n- window: 1280x800 logical at 1x, headless shell (no real display, so no X11/Win32/Cocoa present cost is included)\n\n",
		time.Now().UTC().Format("2006-01-02 15:04 UTC"), gitHead(root), runtime.Version(), runtime.GOOS, runtime.GOARCH, runtime.GOMAXPROCS(0), cpuModel(), uiName)

	site := startSite()
	defer site.Close()

	bin := buildBinary(root)
	defer os.RemoveAll(filepath.Dir(bin))

	if !*onlyChrome {
		coldStart(r, bin, site.URL, runs)
		memory(r, bin, site.URL)
		inProcess(r, chromeFS, site.URL, samples)
		chromeAt2x(r, chromeFS, site.URL, samples)
		engineSection(r, samples)
		chromeRepaintSection(r)
		suggestBench(r)
		micro(r)
	}
	if !*noChrome {
		compareChromium(r, bin, site.URL, *chromium, runs)
	}
	r.f("\n## How to compare with Chrome\n\n")
	r.f("`bench/gui_vs_chromium.sh` (or the Chromium section above, which this program runs when a Chromium binary is found) launches headless Chromium on the same local fixture pages and records (a) wall time from exec to a finished `--screenshot`, and (b) peak resident and proportional (PSS) memory summed over the whole process tree with 1 and 10 tabs open. Chromium is multi-process, so a single-process RSS is not comparable; PSS summed over the tree is the fair figure.\n\n")
	r.f("What the comparison does **not** show: Chromium here is headless and draws no browser UI (tab strip, omnibox, sidebar), while Sweef's number includes painting its entire chrome through its own engine; Chromium renders far more of the web correctly. Do not quote the ratio without those caveats. Use `-skip-chromium` to omit it.\n")
	if err := os.WriteFile(*out, []byte(r.sb.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Println("wrote", *out)
}

// ---- helpers ------------------------------------------------------------------------

func moduleRoot() string {
	dir, _ := os.Getwd()
	for d := dir; d != "/" && d != "."; d = filepath.Dir(d) {
		if _, err := os.Stat(filepath.Join(d, "go.mod")); err == nil {
			return d
		}
	}
	return dir
}

func gitHead(root string) string {
	c := exec.Command("git", "rev-parse", "--short", "HEAD")
	c.Dir = root
	b, err := c.Output()
	if err != nil {
		return "unknown"
	}
	s := strings.TrimSpace(string(b))
	if st, _ := exec.Command("git", "-C", root, "status", "--porcelain").Output(); len(st) > 0 {
		s += "+dirty"
	}
	return s
}

func cpuModel() string {
	b, err := os.ReadFile("/proc/cpuinfo")
	if err != nil {
		return runtime.GOARCH
	}
	for _, l := range strings.Split(string(b), "\n") {
		if strings.HasPrefix(l, "model name") {
			if i := strings.Index(l, ":"); i > 0 {
				return fmt.Sprintf("%s (%d logical CPUs)", strings.TrimSpace(l[i+1:]), runtime.NumCPU())
			}
		}
	}
	return runtime.GOARCH
}

func buildBinary(root string) string {
	dir, _ := os.MkdirTemp("", "appbench-")
	bin := filepath.Join(dir, "sweef")
	c := exec.Command("go", "build", "-ldflags=-s -w", "-o", bin, "./cmd/sweef")
	c.Dir = root
	c.Env = append(os.Environ(), "CGO_ENABLED=0")
	if out, err := c.CombinedOutput(); err != nil {
		fmt.Fprintf(os.Stderr, "build failed: %v\n%s", err, out)
		os.Exit(1)
	}
	return bin
}

func percentile(ds []time.Duration, p float64) time.Duration {
	if len(ds) == 0 {
		return 0
	}
	c := append([]time.Duration(nil), ds...)
	sort.Slice(c, func(i, j int) bool { return c[i] < c[j] })
	return c[int(p*float64(len(c)-1))]
}

func ms(d time.Duration) string { return fmt.Sprintf("%.2f ms", float64(d.Microseconds())/1000) }

func medianF(v []float64) float64 {
	if len(v) == 0 {
		return 0
	}
	c := append([]float64(nil), v...)
	sort.Float64s(c)
	return c[len(c)/2]
}

