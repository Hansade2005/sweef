// Command appbench measures the GUI stack and writes internal/app/BENCH.md.
//
//	go run ./internal/app/cmd/appbench            # everything, ~2 minutes
//	go run ./internal/app/cmd/appbench -quick     # fewer samples
//	go run ./internal/app/cmd/appbench -ui DIR    # bench another chrome UI (a directory laid out like ui.FS)
//
// Every number in the report comes from this program running on this
// machine. Nothing is estimated. Cold-start and RSS are measured in child
// processes (`sweef gui --headless --stats`); latencies are measured
// in-process through the headless shell (shell event pushed -> Present
// called).
