// ---- cold start (child processes) -----------------------------------------------------

type runResult struct {
	wall        time.Duration
	firstFrame  time.Duration
	rssMiB      float64 // last memory line
	rssFirst    float64 // first memory line
	tabs        int
	frames      int
	chromeP50   time.Duration
	pageP50     time.Duration
	composeP50  time.Duration
	rssIsExact  bool
	heapMiB     float64
	goroutines  int
	stdoutTrace string
}

func parseStats(out string) (r runResult) {
	for _, l := range strings.Split(out, "\n") {
		f := strings.Fields(l)
		switch {
		case strings.HasPrefix(l, "first frame"):
			r.firstFrame = parseMS(f[2])
		case strings.HasPrefix(l, "memory"):
			// memory           104.7 MiB (RSS), heap 47.1 MiB, 13 goroutines, 1 tabs
			r.rssMiB, _ = strconv.ParseFloat(f[1], 64)
			if r.rssFirst == 0 {
				r.rssFirst = r.rssMiB
			}
			r.rssIsExact = strings.Contains(l, "(RSS)")
			for i, x := range f {
				if x == "heap" && i+1 < len(f) {
					r.heapMiB, _ = strconv.ParseFloat(f[i+1], 64)
				}
				if x == "goroutines," && i > 0 {
					r.goroutines, _ = strconv.Atoi(f[i-1])
				}
				if x == "tabs" && i > 0 {
					r.tabs, _ = strconv.Atoi(f[i-1])
				}
			}
		case strings.HasPrefix(l, "paint chrome"):
			r.chromeP50 = parseMS(f[3])
		case strings.HasPrefix(l, "paint page"):
			r.pageP50 = parseMS(f[3])
		case strings.HasPrefix(l, "frames presented"):
			r.frames, _ = strconv.Atoi(f[2])
		}
	}
	return
}

func parseMS(s string) time.Duration {
	s = strings.TrimSuffix(s, "ms")
	v, _ := strconv.ParseFloat(s, 64)
	return time.Duration(v * float64(time.Millisecond))
}

func runSweef(bin string, args ...string) (runResult, error) {
	t0 := time.Now()
	c := exec.Command(bin, args...)
	out, err := c.CombinedOutput()
	r := parseStats(string(out))
	r.wall = time.Since(t0)
	r.stdoutTrace = string(out)
	return r, err
}

func coldStart(r *report, bin, site string, runs int) {
	fmt.Println("cold start ...")
	var cold, warm []runResult
	for i := 0; i < runs; i++ {
		prof, _ := os.MkdirTemp("", "appbench-prof-")
		defer os.RemoveAll(prof)
		args := []string{"gui", "--headless", "--size", "1280x800", "--profile", prof, "--no-restore", "--stats", site + "/"}
		res, err := runSweef(bin, args...) // empty profile: no bytecode cache yet
		if err != nil {
			fmt.Fprintln(os.Stderr, "cold run failed:", err, res.stdoutTrace)
			continue
		}
		cold = append(cold, res)
		res2, err := runSweef(bin, args...) // same profile: bytecode cache populated
		if err == nil {
			warm = append(warm, res2)
		}
	}
	sum := func(rs []runResult, f func(runResult) time.Duration) (time.Duration, time.Duration) {
		var v []time.Duration
		for _, x := range rs {
			v = append(v, f(x))
		}
		return percentile(v, 0.5), percentile(v, 1)
	}
	r.f("## Cold start\n\n")
	r.f("`sweef gui --headless --size 1280x800 --stats <local article page>` as a fresh process, %d runs each. \"First frame\" is the time from `app.New` to the first Present that contains the painted chrome. \"Process wall\" includes process start, loading the page, waiting for idle and printing stats (it is an upper bound on time-to-interactive, dominated by the idle wait of 200 ms plus page load).\n\n", runs)
	r.f("| scenario | first frame median | first frame max | process wall median |\n|---|---|---|---|\n")
	for _, row := range []struct {
		name string
		rs   []runResult
	}{{"empty profile (no bytecode cache)", cold}, {"second launch (bytecode cache warm)", warm}} {
		m, mx := sum(row.rs, func(x runResult) time.Duration { return x.firstFrame })
		w, _ := sum(row.rs, func(x runResult) time.Duration { return x.wall })
		measured[row.name] = msf(m)
		r.f("| %s | %s | %s | %s |\n", row.name, ms(m), ms(mx), ms(w))
	}
	r.f("\n")
}

func memory(r *report, bin, site string) {
	fmt.Println("memory ...")
	r.f("## Memory (RSS of the whole sweef process)\n\n")
	r.f("Measured from `/proc/self/status` inside the process (`sweef gui --headless --stats`). Sweef is one process: the engine, chrome page, every tab and the compositor share it. \"just loaded\" is half a second after the pages finished loading, when painting garbage is still resident; \"idle 3 s\" is after the idle trim (a GC plus returning freed pages to the OS, which the app does once after one quiet second).\n\n")
	r.f("| open page tabs | RSS just loaded | RSS idle 3 s | Go heap idle | goroutines |\n|---|---|---|---|---|\n")
	for _, n := range []int{1, 10} {
		var rss, rssIdle []float64
		var last runResult
		for i := 0; i < 3; i++ {
			steps := []string{`{"wait":"idle"}`}
			for k := 1; k < n; k++ {
				steps = append(steps, fmt.Sprintf(`{"newtab":"%s/a/%d"}`, site, k))
			}
			steps = append(steps, `{"wait":"idle"}`, `{"wait":"500ms"}`, `{"print":"stats"}`, `{"wait":"2500ms"}`)
			script := `{"steps":[` + strings.Join(steps, ",") + `]}`
			f := filepath.Join(os.TempDir(), "appbench-script.json")
			_ = os.WriteFile(f, []byte(script), 0o644)
			res, err := runSweef(bin, "gui", "--headless", "--size", "1280x800", "--stats", "--script", f, site+"/a/0")
			if err != nil {
				fmt.Fprintln(os.Stderr, "memory run failed:", err, res.stdoutTrace)
				continue
			}
			rssIdle = append(rssIdle, res.rssMiB)
			rss = append(rss, res.rssFirst)
			last = res
		}
		measured[fmt.Sprintf("rss%d", n)] = medianF(rssIdle)
		r.f("| %d | %.1f MiB | %.1f MiB | %.1f MiB | %d |\n", n, medianF(rss), medianF(rssIdle), last.heapMiB, last.goroutines)
	}
	r.f("\n(median of 3 runs; each tab is a ~100 KB article page of 40 sections.)\n\n")
}

// ---- in-process latency -------------------------------------------------------------------

type inproc struct {
	a   *app.App
	win *headless.Window
}

func startApp(chromeFS fs.FS, urls []string, scale float64) *inproc {
	win := headless.New(1280, 800, scale)
	cfg := app.Config{Shell: win, ChromeFS: chromeFS, Profile: store.OpenIncognito(), NoRestore: true, InitialURLs: urls, DownloadsDir: os.TempDir()}
	if chromeFS == nil {
		cfg.ChromeFS = app.PlaceholderFS()
	}
	a, err := app.New(cfg)
	if err != nil {
		panic(err)
	}
	go a.Run(context.Background())
	return &inproc{a, win}
}

func (p *inproc) stop() { p.a.Close() }

func (p *inproc) idle() { p.a.WaitIdle(150*time.Millisecond, 60*time.Second) }

func (p *inproc) key(chord string) {
	for _, e := range headless.KeyEvents(chord) {
		p.win.Push(e)
	}
}

func inProcess(r *report, chromeFS fs.FS, site string, n int) {
	fmt.Println("in-process latency ...")
	p := startApp(chromeFS, []string{site + "/red", site + "/green", site + "/a/1", site + "/link"}, 1)
	defer p.stop()
	p.idle()
	time.Sleep(300 * time.Millisecond)

	r.f("## Input-to-photon latency\n\n")
	r.f("Time from a shell event being pushed to the headless window until the next `Present` call (or, where noted, until the expected pixels are on the screen). %d samples each, 1280x800, 1x. A real shell adds its own copy-to-screen cost, which is not included.\n\n", n)
	r.f("| action | what happens | p50 | p99 | max |\n|---|---|---|---|---|\n")

	row := func(name, what string, ds []time.Duration) {
		r.f("| %s | %s | %s | %s | %s |\n", name, what, ms(percentile(ds, 0.5)), ms(percentile(ds, 0.99)), ms(percentile(ds, 1)))
	}

	// 1. typing in the omnibox: chrome page JS + chrome-strip repaint + compose
	p.key("ctrl+l")
	p.idle()
	var typing []time.Duration
	for i := 0; i < n; i++ {
		ev := shell.Event{Kind: shell.EvText, Text: "a"}
		if i%2 == 1 {
			ev = headless.KeyEvents("Backspace")[0]
		}
		if d, ok := p.win.PushAndMeasure(ev, 3*time.Second); ok {
			typing = append(typing, d)
		}
		p.idle()
	}
	row("keystroke in the omnibox (letter / Backspace)", "chrome page runs its handlers, strip repainted, composed; the dropdown opens and closes on every other key", typing)
	chromeKeys["alt1x"] = typing
	typed := typingSamples(p, n)
	row("typing in the omnibox (dropdown open)", "letters typed one after the other: only the text and the suggestion rows change", typed)
	chromeKeys["typing1x"] = typed

	// 2. wheel scroll: compositor only
	p.key("ctrl+1")
	p.idle()
	p.win.Push(shell.Event{Kind: shell.EvMouseMove, X: 600, Y: 500})
	p.idle()
	var wheel []time.Duration
	p.key("ctrl+3") // the long article
	p.idle()
	for i := 0; i < n; i++ {
		dy := 120.0
		if i%2 == 1 {
			dy = -120
		}
		if d, ok := p.win.PushAndMeasure(shell.Event{Kind: shell.EvWheel, X: 600, Y: 500, DY: dy}, 3*time.Second); ok {
			wheel = append(wheel, d)
		}
		p.idle()
	}
	row("wheel notch over a page", "easing tick + blit from the page texture (engine not involved)", wheel)
	chromeKeys["wheel1x"] = wheel

	// 3. tab switch until the new page's pixels are visible
	var sw []time.Duration
	for i := 0; i < n; i++ {
		target := "#d33a3a"
		keyc := "ctrl+1"
		if i%2 == 1 {
			target, keyc = "#2f9e44", "ctrl+2"
		}
		want, _ := app.ParseColor(target)
		t0 := time.Now()
		p.key(keyc)
		if d, ok := p.win.WaitPixel(t0, 40, 140, func(c color.RGBA) bool { return near(c, want) }, 5*time.Second); ok {
			sw = append(sw, d)
		}
		p.idle()
	}
	row("switch tab (ctrl+N)", "page repainted by the engine into the texture, until its pixels show", sw)
	chromeKeys["switch1x"] = sw

	// 4. cursor shape: hover a link, then leave it (page JS hit test in the tab worker)
	p.key("ctrl+4")
	p.idle()
	var cur []time.Duration
	for i := 0; i < n; i++ {
		want, other := shell.CursorPointer, shell.CursorDefault
		y := 160.0 // inside the 200px link block of the /link page
		if i%2 == 1 {
			want, other = shell.CursorDefault, shell.CursorPointer
			y = 600
		}
		_ = other
		t0 := time.Now()
		p.win.Push(shell.Event{Kind: shell.EvMouseMove, X: 100, Y: y})
		for time.Since(t0) < 2*time.Second && p.win.Cursor() != want {
			time.Sleep(50 * time.Microsecond)
		}
		if p.win.Cursor() == want {
			cur = append(cur, time.Since(t0))
		}
		p.idle()
	}
	row("pointer move (cursor shape change)", "hit test + page JS cursor lookup + SetCursor (no pixels change)", cur)
	r.f("\n")

	st := p.a.Stats()
	r.f("## Frame timing (`sweef gui --stats` numbers from the run above)\n\n")
	r.f("| stage | p50 | p99 | max | samples |\n|---|---|---|---|---|\n")
	r.f("| compose (chrome + page + overlay blend into the frame) | %s | %s | %s | %d |\n", ms(st.Compositor.Compose.P50), ms(st.Compositor.Compose.P99), ms(st.Compositor.Compose.Max), st.Compositor.Compose.N)
	for _, k := range []string{"chrome: style + layout", "chrome: raster", "chrome: input handler (JS)"} {
		if pp, ok := st.Compositor.Paint[k]; ok {
			measured[k+" p50"], measured[k+" p99"] = msf(pp.P50), msf(pp.P99)
		}
	}
	var kinds []string
	for k := range st.Compositor.Paint {
		kinds = append(kinds, k)
	}
	sort.Strings(kinds)
	for _, k := range kinds {
		pp := st.Compositor.Paint[k]
		r.f("| engine paint: %s | %s | %s | %s | %d |\n", k, ms(pp.P50), ms(pp.P99), ms(pp.Max), pp.N)
	}
	r.f("| input event to Present (all inputs above) | %s | %s | %s | %d |\n", ms(st.InputLatency.P50), ms(st.InputLatency.P99), ms(st.InputLatency.Max), st.InputLatency.N)
	r.f("\nAverage damage per presented frame: %d px of %d (%.1f%%).\n\n", st.DamageAvgPx, 1280*800, 100*float64(st.DamageAvgPx)/float64(1280*800))
	// sidebar open: full-height chrome paint
	p.key("ctrl+shift+a")
	p.idle()
	time.Sleep(200 * time.Millisecond)
	var side []time.Duration
	p.key("ctrl+l")
	p.idle()
	for i := 0; i < n/2; i++ {
		ev := shell.Event{Kind: shell.EvText, Text: "b"}
		if i%2 == 1 {
			ev = headless.KeyEvents("Backspace")[0]
		}
		if d, ok := p.win.PushAndMeasure(ev, 3*time.Second); ok {
			side = append(side, d)
		}
		p.idle()
	}
	r.f("With the sidebar open (chrome painted at full window height): keystroke latency p50 %s, p99 %s.\n\n", ms(percentile(side, 0.5)), ms(percentile(side, 0.99)))

}

// chromeKeys collects the chrome latency samples the before/after table needs.
var chromeKeys = map[string][]time.Duration{}

// typingSamples types letters one after the other into the omnibox (after a
// first one that opens the dropdown), clearing the field now and then.
func typingSamples(p *inproc, n int) []time.Duration {
	p.key("ctrl+a")
	p.win.Push(headless.KeyEvents("Backspace")[0])
	p.idle()
	for _, e := range headless.TypeEvents("sw") {
		p.win.Push(e)
	}
	p.idle()
	var out []time.Duration
	for i := 0; i < n; i++ {
		if i%16 == 15 {
			p.key("ctrl+a")
			for _, e := range headless.TypeEvents("sw") {
				p.win.Push(e)
			}
			p.idle()
		}
		if d, ok := p.win.PushAndMeasure(shell.Event{Kind: shell.EvText, Text: string(rune('a' + i%26))}, 3*time.Second); ok {
			out = append(out, d)
		}
		p.idle()
	}
	return out
}

// chromeAt2x measures the chrome interactions on a 2x (HiDPI) window.
func chromeAt2x(r *report, chromeFS fs.FS, site string, n int) {
	fmt.Println("in-process latency at 2x ...")
	p := startApp(chromeFS, []string{site + "/red", site + "/green", site + "/a/1", site + "/link"}, 2)
	defer p.stop()
	p.idle()
	time.Sleep(300 * time.Millisecond)
	r.f("## Chrome latency on a 2x (HiDPI) window\n\n")
	r.f("The same omnibox interactions on a 2560x1600 device-pixel window (scale 2). %d samples each.\n\n", n)
	r.f("| action | p50 | p99 | max |\n|---|---|---|---|\n")
	p.key("ctrl+l")
	p.idle()
	var alt []time.Duration
	for i := 0; i < n; i++ {
		ev := shell.Event{Kind: shell.EvText, Text: "a"}
		if i%2 == 1 {
			ev = headless.KeyEvents("Backspace")[0]
		}
		if d, ok := p.win.PushAndMeasure(ev, 3*time.Second); ok {
			alt = append(alt, d)
		}
		p.idle()
	}
	chromeKeys["alt2x"] = alt
	typed := typingSamples(p, n)
	chromeKeys["typing2x"] = typed
	var sw []time.Duration
	for i := 0; i < n; i++ {
		target, keyc := "#d33a3a", "ctrl+1"
		if i%2 == 1 {
			target, keyc = "#2f9e44", "ctrl+2"
		}
		want, _ := app.ParseColor(target)
		t0 := time.Now()
		p.key(keyc)
		if d, ok := p.win.WaitPixel(t0, 80, 280, func(c color.RGBA) bool { return near(c, want) }, 5*time.Second); ok {
			sw = append(sw, d)
		}
		p.idle()
	}
	chromeKeys["switch2x"] = sw
	row := func(name string, ds []time.Duration) {
		r.f("| %s | %s | %s | %s |\n", name, ms(percentile(ds, 0.5)), ms(percentile(ds, 0.99)), ms(percentile(ds, 1)))
	}
	row("keystroke in the omnibox (letter / Backspace)", alt)
	row("typing in the omnibox (dropdown open)", typed)
	row("switch tab (ctrl+N)", sw)
	r.f("\n")
	st := p.a.Stats()
	r.f("Where a chrome repaint goes on the 2x window (engine side, from `sweef gui --stats`): ")
	for _, k := range []string{"chrome: style + layout", "chrome: raster"} {
		if pp, ok := st.Compositor.Paint[k]; ok {
			r.f("%s p50 %s / p99 %s; ", k, ms(pp.P50), ms(pp.P99))
		}
	}
	r.f("\n\n")
}

func near(c, w color.RGBA) bool {
	d := func(a, b uint8) int {
		if a > b {
			return int(a - b)
		}
		return int(b - a)
	}
	return d(c.R, w.R) < 4 && d(c.G, w.G) < 4 && d(c.B, w.B) < 4
}
