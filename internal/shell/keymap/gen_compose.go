//go:build ignore

// gen_compose writes compose_table.go: for every dead-key combining mark (deadKeys in keysym.go) and every code point,
// the single code point that NFC composes the pair to, if there is one. keysym.go used golang.org/x/text/unicode/norm
// for this, which links 105 KB of normalization tables into the browser for fifteen accents.
//
//	go generate ./internal/shell/keymap
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"

	"golang.org/x/text/unicode/norm"
)

// The combining marks of the dead keysyms in keysym.go.
var marks = []rune{0x300, 0x301, 0x302, 0x303, 0x304, 0x306, 0x307, 0x308, 0x30a, 0x30b, 0x30c, 0x327, 0x328, 0x323, 0x309, 0x31b}

func main() {
	type ent struct {
		key uint32 // comb<<16 | base
		out rune
	}
	var es []ent
	for _, comb := range marks {
		for base := rune(0); base <= 0x10ffff; base++ {
			if base >= 0xd800 && base < 0xe000 {
				continue
			}
			s := norm.NFC.String(string([]rune{base, comb}))
			if r := []rune(s); len(r) == 1 {
				if comb > 0xffff || base > 0xffff || r[0] > 0xffff {
					panic(fmt.Sprintf("outside the BMP: %U + %U = %U", base, comb, r[0]))
				}
				es = append(es, ent{uint32(comb)<<16 | uint32(base), r[0]})
			}
		}
	}
	sort.Slice(es, func(i, j int) bool { return es[i].key < es[j].key })
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_compose.go; DO NOT EDIT.\n\npackage keymap\n\n")
	b.WriteString("// composeKeys[i] is comb<<16|base and composeOut[i] the code point NFC makes of the pair, sorted by key.\n")
	b.WriteString("var composeKeys = [...]uint32{")
	for i, e := range es {
		if i%8 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "0x%08x,", e.key)
	}
	b.WriteString("\n}\n\nvar composeOut = [...]uint16{")
	for i, e := range es {
		if i%12 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "0x%04x,", e.out)
	}
	b.WriteString("\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("compose_table.go", src, 0o644); err != nil {
		panic(err)
	}
}
